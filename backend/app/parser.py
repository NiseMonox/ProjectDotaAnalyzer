# Process-wide concurrency limit for JVM parses. A threading semaphore (polled
# without blocking) works across event loops and threads, and an abandoned wait
# (task cancellation) never leaks a permit.
_clarity_slots: threading.BoundedSemaphore | None = None
_clarity_slots_lock = threading.Lock()


def _get_clarity_slots() -> threading.BoundedSemaphore:
    global _clarity_slots
    with _clarity_slots_lock:
        if _clarity_slots is None:
            _clarity_slots = threading.BoundedSemaphore(_env_int("CLARITY_MAX_CONCURRENCY", 1))
        return _clarity_slots


class _ClaritySlot:
    """Async context manager holding one Clarity concurrency permit."""

    def __init__(self) -> None:
        self._sem: threading.BoundedSemaphore | None = None

    async def __aenter__(self) -> "_ClaritySlot":
        sem = _get_clarity_slots()
        while not sem.acquire(blocking=False):
            await asyncio.sleep(_SLOT_POLL_INTERVAL_S)
        self._sem = sem
        return self

    async def __aexit__(self, *exc_info: Any) -> None:
        if self._sem is not None:
            self._sem.release()
            self._sem = None


# java -version probe results, keyed by java executable: (usable, monotonic time
# of the probe). A success is kept for the life of the process; a failure is
# retried after _JAVA_PROBE_RETRY_S, so one transient failure (e.g. a timeout on
# a loaded VM during startup) does not disable replay parsing until a restart.
_java_probe: dict[str, tuple[bool, float]] = {}
_java_probe_lock = threading.Lock()  # one probe at a time; held by worker threads only
_JAVA_PROBE_RETRY_S = 300.0


def _run_java_version(java_path: str) -> bool:
    try:
        result = subprocess.run(
            [java_path, "-version"], capture_output=True, text=True, timeout=30, check=False,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        logger.warning("Java runtime not usable at %s: %s", java_path, exc)
        return False
    if result.returncode != 0:
        logger.warning("'%s -version' exited with %s", java_path, result.returncode)
        return False
    match = re.search(r'version "(\d+)(?:\.(\d+))?', (result.stderr or "") + (result.stdout or ""))
    if match:
        major = int(match.group(1))
        if major == 1 and match.group(2):  # "1.8.0" style
            major = int(match.group(2))
        if major < _MIN_JAVA_MAJOR:
            logger.warning("Java %s found at %s; clarity needs Java %s+", major, java_path, _MIN_JAVA_MAJOR)
            return False
    return True


def _cached_java_probe(java_path: str) -> bool | None:
    """Cached probe result, or None when the probe has to run (again).

    Lock-free on purpose (a dict read is atomic): the event loop must never
    wait for a probe that a worker thread is running.
    """
    cached = _java_probe.get(java_path)
    if cached is None:
        return None
    ok, probed_at = cached
    if not ok and time.monotonic() - probed_at >= _JAVA_PROBE_RETRY_S:
        return None
    return ok


def _java_ok(java_path: str) -> bool:
    """Whether ``java_path`` is a usable Java 17+ runtime (cached, see ``_java_probe``).

    Blocks while ``java -version`` runs; async code calls it through
    :func:`check_clarity_available`.
    """
    cached = _cached_java_probe(java_path)
    if cached is not None:
        return cached
    with _java_probe_lock:
        cached = _cached_java_probe(java_path)  # probed while we waited for the lock
        if cached is not None:
            return cached
        ok = _run_java_version(java_path)
        _java_probe[java_path] = (ok, time.monotonic())
        if ok:
            logger.info("Java runtime available for the clarity parser: %s", java_path)
        return ok


def reset_clarity_probe_cache() -> None:
    """Forget cached Java probe results (tests / after installing Java)."""
    with _java_probe_lock:
        _java_probe.clear()


async def check_clarity_available(jar_path: Path | None = None, java_path: str | None = None) -> bool:
    """Whether the clarity parser can run (analyzer JAR present and Java 17+ usable).

    ``java -version`` runs in a worker thread and its result is cached (a
    success for the life of the process, a failure for a few minutes); the JAR
    check is a cheap stat on every call. Never blocks the event loop, also
    while another caller's probe is still running.
    """
    jar = Path(jar_path or CLARITY_JAR_PATH)
    java = java_path or JAVA_PATH
    if not jar.is_file():
        return False
    cached = _cached_java_probe(java)
    if cached is not None:
        return cached
    return await asyncio.to_thread(_java_ok, java)


# PIDs of running analyzer JVMs. Each one leads its own session/process group
# (so a timeout can kill the whole group), which also means it does not get the
# terminal's or the service manager's signals when the server goes away.
_live_clarity_pids: set[int] = set()
# ... and those kill_running_parsers() stopped: their parse did not fail
# because of the replay.
_stopped_clarity_pids: set[int] = set()
_live_clarity_pids_lock = threading.Lock()


def _signal_kill(pid: int) -> None:
    """SIGKILL a child process (its whole process group on POSIX)."""
    try:
        if os.name == "posix":
            os.killpg(pid, signal.SIGKILL)
        else:
            os.kill(pid, signal.SIGTERM)
    except OSError:  # already gone, or not ours any more
        pass


def kill_running_parsers() -> int:
    """Kill every analyzer JVM this process started that is still running.

    Registered with ``atexit`` so a server that exits without cancelling its
    request tasks (dev reload, Ctrl-C, SIGTERM) does not leave JVMs behind; the
    server also calls it from its shutdown hook. Returns the number killed.
    A parse that is still being awaited then ends with
    :class:`ParserUnavailableError`, not :class:`ReplayParseError`: nothing
    is wrong with its replay, so a stored replay that was being re-parsed is
    kept and parsed again after the restart. The client that waited for the
    parse does not get this error from a real server: uvicorn runs the
    shutdown hook only after the open requests have ended or, once
    ``--timeout-graceful-shutdown`` ran out, were cancelled (that client
    sees a dropped connection or a plain 500). A SIGKILL of the server
    itself cannot be handled this way.
    """
    with _live_clarity_pids_lock:
        pids = list(_live_clarity_pids)
        _live_clarity_pids.clear()
        _stopped_clarity_pids.update(pids)
    for pid in pids:
        _signal_kill(pid)
    return len(pids)


atexit.register(kill_running_parsers)


async def _kill_process(proc: asyncio.subprocess.Process) -> None:
    """Kill a child process (and its process group on POSIX) and reap it."""
    if proc.returncode is not None:
        return
    try:
        if os.name == "posix":
            os.killpg(proc.pid, signal.SIGKILL)
        else:
            proc.kill()
    except ProcessLookupError:
        pass
    except OSError:
        try:
            proc.kill()
        except ProcessLookupError:
            pass
    try:
        await asyncio.wait_for(proc.wait(), timeout=10)
    except asyncio.TimeoutError:
        logger.warning("Clarity process %s did not exit after SIGKILL", proc.pid)


async def _run_subprocess(cmd: list[str], timeout: float) -> tuple[bytes, bytes, int]:
    """Run ``cmd`` capturing output; kill it on timeout or task cancellation."""
    kwargs: dict[str, Any] = {}
    if os.name == "posix":
        kwargs["start_new_session"] = True  # own process group -> killpg on timeout
    try:
        proc = await asyncio.create_subprocess_exec(
            *cmd,
            stdin=asyncio.subprocess.DEVNULL,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            **kwargs,
        )
    except FileNotFoundError as exc:
        raise ParserUnavailableError("Java runtime not found; the replay parser is unavailable") from exc
    except OSError as exc:
        logger.error("Failed to start the clarity parser: %s", exc)
        raise ParserUnavailableError("The replay parser could not be started") from exc

    with _live_clarity_pids_lock:
        _live_clarity_pids.add(proc.pid)
    try:
        stdout, stderr = await asyncio.wait_for(proc.communicate(), timeout=timeout)
    except asyncio.TimeoutError:
        await _kill_process(proc)
        raise ReplayParseError("Replay parsing timed out") from None
    except asyncio.CancelledError:
        await _kill_process(proc)
        raise
    finally:
        with _live_clarity_pids_lock:
            _live_clarity_pids.discard(proc.pid)
            stopped = proc.pid in _stopped_clarity_pids
            _stopped_clarity_pids.discard(proc.pid)
    if stopped:
        raise ParserUnavailableError("The replay parser was stopped")
    return stdout, stderr, proc.returncode if proc.returncode is not None else -1


def _tail(text: str, limit: int = _STDERR_LOG_LIMIT) -> str:
    lines = [ln for ln in text.splitlines() if not ln.startswith("Picked up JAVA_TOOL_OPTIONS")]
    text = "\n".join(lines).strip()
    return text if len(text) <= limit else "..." + text[-limit:]


