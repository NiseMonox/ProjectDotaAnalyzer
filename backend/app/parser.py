def _as_int(value: Any, default: int = 0) -> int:
    if value is None or isinstance(value, bool):
        return int(value) if isinstance(value, bool) else default
    if isinstance(value, int):
        return value
    try:
        f = float(value)
    except (TypeError, ValueError):
        return default
    if math.isnan(f) or math.isinf(f):
        return default
    return int(f)


def _as_float(value: Any, default: float = 0.0) -> float:
    try:
        f = float(value)
    except (TypeError, ValueError):
        return default
    if math.isnan(f) or math.isinf(f):
        return default
    return f


def _dicts(value: Any) -> list[dict]:
    """Only the dict entries of a JSON list (tolerates None / malformed data)."""
    if not isinstance(value, list):
        return []
    return [v for v in value if isinstance(v, dict)]


def _int_dict(value: Any) -> dict[str, int]:
    if not isinstance(value, dict):
        return {}
    return {str(k): _as_int(v) for k, v in value.items()}


def _team_for_slot(slot: int) -> str:
    return "radiant" if slot < 128 else "dire"


def _hero_name_index(heroes: Iterable[tuple[str, str]]) -> dict[str, str]:
    """normalized slug / display name -> hero_name, for the (hero_name, hero_slug) pairs of a match."""
    index: dict[str, str] = {}
    for name, slug in heroes:
        for key in (slug, name):
            norm = normalize_hero_key(key)
            if norm:
                index.setdefault(norm, name)
    return index


def _unit_keyed(values: Any, hero_names: dict[str, str], heroes_only: bool = False,
                add_npc_prefix: bool = False) -> dict[str, int]:
    """Re-key a {unit: amount} dict to the shared contract.

    Heroes of the match are keyed by ``PlayerData.hero_name`` whatever form the
    source used (slug, npc name, display name); other units keep their unit
    name, or are dropped with ``heroes_only``. ``add_npc_prefix`` puts back
    the "npc_dota_" a source cut off its unit names (the replay analyzer);
    OpenDota's names are complete, also those outside that namespace
    ("dota_fountain", "illusion_npc_dota_hero_viper").
    """
    out: dict[str, int] = {}
    for unit, amount in _int_dict(values).items():
        hero = hero_names.get(normalize_hero_key(unit))
        if hero:
            key = hero
        elif heroes_only:
            continue
        elif add_npc_prefix and not unit.startswith("npc_dota_"):
            key = f"npc_dota_{unit}"
        else:
            key = unit
        out[key] = out.get(key, 0) + amount
    return out


# Inflictor of a plain attack: the code every backend emits, and the raw
# values that mean the same (Clarity "dota_unknown" / empty, OpenDota "null").
ATTACK_INFLICTOR = "attack"
_ATTACK_INFLICTOR_ALIASES = {"", "null", "dota_unknown"}


def _inflictor_key(key: Any) -> str:
    k = str(key if key is not None else "")
    return ATTACK_INFLICTOR if k in _ATTACK_INFLICTOR_ALIASES else k


def _inflictor_dict(value: Any) -> dict[str, int]:
    out: dict[str, int] = {}
    for key, amount in _int_dict(value).items():
        key = _inflictor_key(key)
        out[key] = out.get(key, 0) + amount
    return out


def _per_minute(values: Any, duration: int) -> list[int]:
    """A per-minute series cut at game end (minute 0 .. floor(duration / 60)).

    Analyzer output before schema 3 kept sampling during the post-game.
    """
    series = [_as_int(v) for v in (values or [])] if isinstance(values, list) else []
    if duration > 0:
        del series[duration // 60 + 1:]
    return series


# Gold a hero can earn in lane by 10:00 (OpenDota's lane-efficiency constant)
_LANE_GOLD_AT_TEN = 4948


def lane_efficiency(gold_t: list[int]) -> tuple[float, float]:
    """(lane_efficiency, lane_efficiency_pct) from a per-minute gold series."""
    if len(gold_t) <= 10:
        return 0.0, 0.0
    eff = gold_t[10] / _LANE_GOLD_AT_TEN
    return eff, float(int(eff * 100))


def kill_participation(kills: int, assists: int, team_kills: int) -> float:
    """Share of the team's kills a player took part in (fallback for teamfight_participation)."""
    return min(1.0, (kills + assists) / team_kills) if team_kills > 0 else 0.0


# Kills of one hero at most this many seconds apart form a multi-kill
_MULTI_KILL_WINDOW_S = 18


def kill_announcements(kills_log: list[KillEvent], player_slot: int) -> tuple[dict[str, int], dict[str, int]]:
    """(multi_kills, kill_streaks) of a player, counted from the kill log.

    The game's rules: every kill within 18 s of the hero's previous one
    extends a multi-kill (announced from 2), every kill without dying in
    between extends a streak (announced from 3). On real replays this equals
    the game's own announcements.
    """
    multi: Counter = Counter()
    streaks: Counter = Counter()
    streak = chain = 0
    last_kill: float | None = None
    for kill in kills_log:
        if kill.victim_slot == player_slot:
            streak = 0
        if kill.killer_slot != player_slot or kill.deny:
            continue
        streak += 1
        if streak >= 3:
            streaks[str(streak)] += 1
        chain = chain + 1 if last_kill is not None and kill.time - last_kill <= _MULTI_KILL_WINDOW_S else 1
        if chain >= 2:
            multi[str(chain)] += 1
        last_kill = kill.time
    return dict(multi), dict(streaks)


def _time_log(value: Any) -> list[dict]:
    """``[{time}]`` entries in time order (buyback logs)."""
    return sorted(({"time": _as_int(e.get("time"))} for e in _dicts(value)), key=lambda e: e["time"])


# Ward lifetimes in seconds (fallback when the source does not say why a ward died)
_WARD_LIFETIME_S = game_constants.WARD_LIFETIME_S


def _ward_fell_early(ward_type: str, placed: int, destroyed: int | None) -> bool:
    """Whether a ward died clearly before its expiry (it did not run out)."""
    if destroyed is None:
        return False
    return destroyed - placed < _WARD_LIFETIME_S.get(ward_type, game_constants.OBSERVER_WARD_DURATION_S) - 5


def _dewarded_by_lifetime(ward_type: str, placed: int, destroyed: int | None) -> bool:
    """Lifetime heuristic: a ward that died clearly before its expiry was dewarded."""
    return _ward_fell_early(ward_type, placed, destroyed)


