class ClarityParser(ReplayParser):
    """Parse replays with the clarity Java analyzer.

    Requires a Java 17+ runtime and tools/clarity-analyzer.jar
    (``bash tools/setup_parser.sh``).
    """

    def __init__(self, jar_path: Path | None = None, java_path: str | None = None):
        self.jar_path = Path(jar_path or CLARITY_JAR_PATH)
        self.java_path = java_path or JAVA_PATH

    def name(self) -> str:
        return "clarity"

    def unavailable_reason(self) -> str | None:
        """Why this parser cannot run (None when it can). Uses the cached Java probe."""
        if not self.jar_path.is_file():
            return "Replay parser is not installed (clarity-analyzer.jar missing)"
        if not _java_ok(self.java_path):
            return "Java 17+ runtime not found; the replay parser is unavailable"
        return None

    def _check_requirements(self) -> None:
        """Deprecated sync check kept for older callers; raises ParserUnavailableError."""
        reason = self.unavailable_reason()
        if reason:
            raise ParserUnavailableError(reason)

    def _command(self, file_path: str) -> list[str]:
        return [
            self.java_path,
            f"-Xmx{_jvm_xmx()}",
            "-XX:+ExitOnOutOfMemoryError",
            "-Dfile.encoding=UTF-8",
            "-jar",
            str(self.jar_path),
            str(file_path),
        ]

    async def parse(self, file_path: str) -> MatchData:
        if not self.jar_path.is_file():
            raise ParserUnavailableError("Replay parser is not installed (clarity-analyzer.jar missing)")
        replay_name = Path(file_path).name
        timeout = _clarity_timeout_s()
        started = time.monotonic()

        async with _ClaritySlot():
            stdout, stderr, returncode = await _run_subprocess(self._command(file_path), timeout)

        stderr_text = stderr.decode("utf-8", errors="replace")
        elapsed = time.monotonic() - started
        if returncode != 0:
            logger.warning(
                "Clarity parser failed for %s (exit %s, %.1fs): %s",
                replay_name, returncode, elapsed, _tail(stderr_text),
            )
            if returncode == 3:
                logger.warning("Raise CLARITY_JVM_XMX (currently %s) if replays run out of memory", _jvm_xmx())
            raise ReplayParseError(_EXIT_MESSAGES.get(returncode, "Replay parsing failed"))

        logger.info("Parsed %s with clarity in %.1fs", replay_name, elapsed)
        # Decoding several MB of JSON and building the models takes a few
        # hundred ms: keep it off the event loop.
        return await asyncio.to_thread(self._decode_and_transform, stdout, stderr_text, replay_name)

    def _decode_and_transform(self, stdout: bytes, stderr_text: str, replay_name: str) -> MatchData:
        """Decode the analyzer's JSON output and build the MatchData (blocking)."""
        try:
            raw = json.loads(stdout.decode("utf-8", errors="replace"))
        except ValueError:
            logger.warning(
                "Clarity parser produced invalid JSON for %s (%d bytes): %s",
                replay_name, len(stdout), _tail(stderr_text),
            )
            raise ReplayParseError("Replay parser produced unreadable output") from None
        if not isinstance(raw, dict):
            raise ReplayParseError("Replay parser produced unreadable output")

        if raw.get("partial"):
            logger.warning("Replay %s is incomplete; returning partial match data", replay_name)
        counts = raw.get("parse_errors") if isinstance(raw.get("parse_errors"), dict) else {}
        handler_errors = {key: n for key, n in counts.items() if key not in _CLARITY_DIAGNOSTICS}
        diagnostics = {key: n for key, n in counts.items() if key in _CLARITY_DIAGNOSTICS}
        if handler_errors:
            logger.info("Clarity handler errors for %s: %s", replay_name, handler_errors)
        if diagnostics:
            logger.info("Clarity diagnostics for %s: %s", replay_name, diagnostics)
        if raw.get("match_id_source") == "game_rules_32bit":
            logger.warning("Replay %s has no file info and the match id was decoded as 32 bits; "
                           "it is reported as unknown", replay_name)
        approximated = sorted({key for p in _dicts(raw.get("players"))
                               for key in ("kda_source", "damage_source") if p.get(key) == "combat_log"})
        if approximated:
            logger.info("Replay %s has no scoreboard data (%s): values are combat-log sums",
                        replay_name, ", ".join(approximated))
        logger.debug("Clarity analyzer %s, stderr for %s: %s",
                     raw.get("analyzer_version") or "before 1.4.0", replay_name, _tail(stderr_text))

        try:
            return self._transform_data(raw)
        except Exception as exc:
            logger.exception("Failed to transform clarity output for %s", replay_name)
            raise ReplayParseError("Replay data could not be processed") from exc

    # -- transform helpers --------------------------------------------------

    @staticmethod
    def _resolve_hero(p: dict, idx: int, lookup: dict[str, dict], hero_map: dict[int, dict]) -> tuple[int, str, str]:
        """(hero_id, display name, slug) from npc/internal name, falling back to hero_id.

        A hero that is missing from the static catalog keeps its internal name
        (prettified for display, unchanged as slug); when nothing identifies it
        the code ``hero_<id>`` / ``unknown_<player index>`` is the name.
        """
        internal = str(p.get("hero_name") or "")
        npc = str(p.get("hero_npc_name") or "")
        for candidate in (npc, internal):
            info = lookup.get(normalize_hero_key(candidate))
            if info:
                return info["id"], info["name"], info["slug"]
        hero_id = _as_int(p.get("hero_id"))
        info = hero_map.get(hero_id) if hero_id else None
        if info:
            return hero_id, info.get("name") or info.get("slug") or internal, info.get("slug", "")
        slug = npc[len("npc_dota_hero_"):] if npc.startswith("npc_dota_hero_") else internal
        if slug and not slug.startswith("unknown"):
            return hero_id, slug.replace("_", " ").title(), slug
        return hero_id, (f"hero_{hero_id}" if hero_id else f"unknown_{idx}"), ""

    def _transform_data(self, raw: dict) -> MatchData:
        """Transform clarity JSON output into our data models.

        Accepts analyzer schema 3 (documented in
        tools/clarity-analyzer/OUTPUT_SCHEMA.md), schema 2 (fields that only
        schema 3 has get defaults or fallbacks) and the pre-v2 output with
        legacy coordinates.
        """
        world = raw.get("coord_space") == "world"
        conv = _as_float if world else _legacy_to_world
        if not world:
            logger.info("Clarity output uses legacy coordinates; converting to world units")
        schema = _as_int(raw.get("schema_version"))
        duration = _as_int(raw.get("duration"))
        partial = bool(raw.get("partial", False))

        hero_lookup = _hero_lookup()
        hero_map = load_hero_map()

        # Heroes first: unit-keyed dicts and events of every player refer to them.
        raw_players = _dicts(raw.get("players"))
        slots = [_as_int(p.get("player_slot"), idx if idx < 5 else 128 + idx - 5)
                 for idx, p in enumerate(raw_players)]
        heroes = [self._resolve_hero(p, idx, hero_lookup, hero_map) for idx, p in enumerate(raw_players)]
        hero_names = _hero_name_index((name, slug) for _id, name, slug in heroes)
        name_by_slot = {slot: name for slot, (_id, name, _slug) in zip(slots, heroes)}
        kills_log = _clarity_kills_log(raw.get("kills_log"), conv, set(slots))

        # Wards are emitted at match level; attach them to their owners below.
        all_wards: list[WardEvent] = []
        for w in _dicts(raw.get("wards")):
            slot = _as_int(w.get("player_slot"), -1)
            team = w.get("team") if w.get("team") in ("radiant", "dire") else ""
            if not team and slot >= 0:
                team = _team_for_slot(slot)
            ward_type = "sentry" if w.get("type") == "sentry" else "observer"
            placed = _as_int(w.get("time"))
            destroyed = _as_int(w["destroyed_time"]) if w.get("destroyed_time") is not None else None
            # Schema 3 says whether an enemy destroyed the ward. Older output,
            # and a death the analyzer could not match in the combat log, only
            # leave the lifetime to go by.
            if isinstance(w.get("dewarded"), bool):
                dewarded = w["dewarded"] and destroyed is not None
            else:
                dewarded = _dewarded_by_lifetime(ward_type, placed, destroyed)
            # Analyzer 1.5.0 also tells an attack of the ward's own side from
            # the expiry; older output leaves a denied ward as "not dewarded".
            denied = w.get("denied") is True and destroyed is not None and not dewarded
            killer = _as_int(w.get("killer_slot"), -1) if w.get("killer_slot") is not None else -1
            all_wards.append(WardEvent(
                ward_type=ward_type,
                x=conv(w.get("x")),
                y=conv(w.get("y")),
                time=placed,
                player_slot=slot,
                destroyed_time=destroyed,
                team=team,
                dewarded=dewarded,
                denied=denied,
                killer_slot=killer if (dewarded or denied) and killer in slots else None,
            ))
        wards_by_slot: dict[int, list[WardEvent]] = {}
        for w in all_wards:
            wards_by_slot.setdefault(w.player_slot, []).append(w)

        players: list[PlayerData] = []
        all_ability_events: list[AbilityEvent] = []

        for idx, p in enumerate(raw_players):
            slot = slots[idx]
            team = _team_for_slot(slot)
            hero_id, hero_name, hero_slug = heroes[idx]

            # Real purchases. "ward_dispenser" rows are observer/sentry stacks
            # merging in the inventory, not purchases (schema 3 omits them).
            purchases = [
                (_as_int(e.get("time")), canonical_item_key(e.get("key")))
                for e in _dicts(p.get("purchase_log") or p.get("item_purchases"))
                if e.get("key")
            ]
            purchases = [(t, key) for t, key in purchases if key != "ward_dispenser"]
            items = [ItemEvent(item_name=item_display_name(key), time=t, item_key=key) for t, key in purchases]
            # Strategy-time purchases have no combat-log row. Schema 3 lists
            # them in purchase_log itself; for older output add what the
            # starting inventory snapshot (at the horn) has beyond the pre-game
            # purchases (multiset difference keeps the real purchases).
            snapshot: list[str] = []
            for s in (p.get("starting_items") or []) if schema < 3 else []:
                key = canonical_item_key(s) if isinstance(s, str) else ""
                if key == "ward_dispenser":  # a merged stack holds both ward types
                    snapshot.extend(("ward_observer", "ward_sentry"))
                elif key:
                    snapshot.append(key)
            if snapshot:
                missing = Counter(snapshot) - Counter(it.item_key for it in items if it.time <= 0)
                for key in snapshot:
                    if missing[key] > 0:
                        items.append(ItemEvent(item_name=item_display_name(key), time=-1, item_key=key))
                        missing[key] -= 1
            items.sort(key=lambda it: it.time)

            skills: list[SkillEvent] = []
            for s in _dicts(p.get("ability_upgrades")):
                key = str(s.get("name") or "")
                if not key or key in _SKIP_ABILITIES or "_release" in key:
                    continue
                skills.append(SkillEvent(
                    ability_name=ability_display_name(key),
                    ability_key=str(s.get("key") or key),
                    level=max(1, _as_int(s.get("level"), 1)),
                    time=_as_int(s.get("time")),
                ))

            ability_events = []
            for a in _dicts(p.get("ability_casts")):
                key = str(a.get("name") or "")
                ability_events.append(AbilityEvent(
                    player_slot=slot,
                    hero_name=hero_name,
                    ability_name=ability_display_name(key) if key else "",
                    ability_key=key,
                    time=_as_int(a.get("time")),
                    target=a.get("target"),
                    x=conv(a["x"]) if a.get("x") is not None else None,
                    y=conv(a["y"]) if a.get("y") is not None else None,
                ))
            all_ability_events.extend(ability_events)

            # End-of-game inventory (keys) from the analyzer. The purchase
            # heuristic only stands in when the real inventory was not read: an
            # empty inventory that was read means the hero ended with no items.
            final_keys = [canonical_item_key(k) for k in (p.get("final_items") or []) if isinstance(k, str) and k]
            if not final_keys and p.get("final_items_source") != "inventory":
                non_consumable = [key for _t, key in purchases
                                  if key not in _CONSUMABLES and not key.startswith("recipe_")]
                final_keys = non_consumable[-6:]
            final_items = [item_display_name(k) for k in final_keys]
            backpack = [canonical_item_key(k) for k in (p.get("backpack") or []) if isinstance(k, str) and k]

            snapshots = [
                LaningSnapshot(
                    time=_as_int(s.get("time")),
                    x=conv(s.get("x")),
                    y=conv(s.get("y")),
                    hp=_as_int(s.get("hp")),
                    max_hp=_as_int(s.get("max_hp")),
                    mana=_as_int(s.get("mana")),
                    max_mana=_as_int(s.get("max_mana")),
                    level=_as_int(s.get("level")),
                    last_hits=_as_int(s.get("last_hits")),
                    denies=_as_int(s.get("denies")),
                    net_worth=_as_int(s.get("net_worth")),
                )
                for s in _dicts(p.get("laning_snapshots"))
            ]
            lane = _as_int(p.get("lane"))
            lane_role = _as_int(p.get("lane_role"))
            is_roaming = bool(p.get("is_roaming", False))
            if not lane:
                lane, lane_role, is_roaming = infer_lane(
                    [(s.x, s.y) for s in snapshots if 60 <= s.time <= 600], team,
                )

            gold_t = _per_minute(p.get("gold_t"), duration)
            lane_eff, lane_eff_pct = lane_efficiency(gold_t)
            player_name = str(p.get("player_name") or "")
            if player_name == f"Player {idx + 1}":  # placeholder of analyzer output before schema 3
                player_name = ""
            kills, assists = _as_int(p.get("kills")), _as_int(p.get("assists"))
            if p.get("teamfight_participation") is not None:  # the game's own counter
                participation = _as_float(p.get("teamfight_participation"))
            else:
                participation = kill_participation(kills, assists, _as_int(raw.get(f"{team}_score")))
            buyback_log = _time_log(p.get("buyback_log"))
            if "multi_kills" in p or "kill_streaks" in p:  # the game's own announcements
                multi_kills, kill_streaks = _int_dict(p.get("multi_kills")), _int_dict(p.get("kill_streaks"))
            else:
                multi_kills, kill_streaks = kill_announcements(kills_log, slot)

            player_wards = sorted(wards_by_slot.get(slot, []), key=lambda w: w.time)
            players.append(PlayerData(
                player_slot=slot,
                hero_id=hero_id,
                hero_name=hero_name,
                hero_slug=hero_slug,
                player_name=player_name,
                team=team,
                kills=kills,
                deaths=_as_int(p.get("deaths")),
                assists=assists,
                level=max(1, _as_int(p.get("level"), 1)),
                last_hits=_as_int(p.get("last_hits")),
                denies=_as_int(p.get("denies")),
                gold_per_min=_as_int(p.get("gold_per_min")),
                xp_per_min=_as_int(p.get("xp_per_min")),
                hero_damage=_as_int(p.get("hero_damage")),
                tower_damage=_as_int(p.get("tower_damage")),
                hero_healing=_as_int(p.get("hero_healing")),
                net_worth=_as_int(p.get("net_worth")),
                items=items,
                backpack=backpack,
                final_items=final_items,
                final_item_keys=final_keys,
                neutral_item=canonical_item_key(p.get("neutral_item")),
                skills=skills,
                wards=player_wards,
                ability_events=ability_events,
                gold_t=gold_t,
                xp_t=_per_minute(p.get("xp_t"), duration),
                lh_t=_per_minute(p.get("lh_t"), duration),
                dn_t=_per_minute(p.get("dn_t"), duration) or _denies_per_minute(snapshots),
                lane=lane,
                lane_role=lane_role,
                is_roaming=is_roaming,
                lane_efficiency=lane_eff,
                lane_efficiency_pct=lane_eff_pct,
                killed=_unit_keyed(p.get("killed"), hero_names, heroes_only=True),
                killed_by=_unit_keyed(p.get("killed_by"), hero_names, heroes_only=True),
                damage=_unit_keyed(p.get("damage"), hero_names, add_npc_prefix=True),
                damage_taken=_unit_keyed(p.get("damage_taken"), hero_names, add_npc_prefix=True),
                damage_inflictor=_inflictor_dict(p.get("damage_inflictor")),
                gold_reasons=_int_dict(p.get("gold_reasons")),
                xp_reasons=_int_dict(p.get("xp_reasons")),
                runes_log=_dicts(p.get("runes_log")),
                runes=_int_dict(p.get("runes")),
                stuns=_as_float(p.get("stuns")),
                actions_per_min=_as_int(p.get("actions_per_min")),
                teamfight_participation=participation,
                buyback_count=len(buyback_log) or _as_int(p.get("buyback_count")),
                buyback_log=buyback_log,
                obs_placed=sum(1 for w in player_wards if w.ward_type == "observer"),
                sen_placed=sum(1 for w in player_wards if w.ward_type == "sentry"),
                observer_kills=_as_int(p.get("observer_kills")),
                sentry_kills=_as_int(p.get("sentry_kills")),
                lane_kills=_as_int(p.get("lane_kills")),
                neutral_kills=_as_int(p.get("neutral_kills")),
                ancient_kills=_as_int(p.get("ancient_kills")),
                tower_kills=_as_int(p.get("tower_kills")),
                roshans_killed=_as_int(p.get("roshans_killed")),
                courier_kills=_as_int(p.get("courier_kills")),
                multi_kills=multi_kills,
                kill_streaks=kill_streaks,
                purchase_log=[{"time": it.time, "key": it.item_key} for it in items],
                position_log=_position_log(p.get("position_log")),
                laning_snapshots=snapshots,
                laning_creep_kills=[LaningCreepKill(**_pick(c, LaningCreepKill)) for c in _dicts(p.get("laning_creep_kills"))],
                laning_denies=[LaningCreepKill(**_pick(d, LaningCreepKill)) for d in _dicts(p.get("laning_denies"))],
                laning_damage_events=[
                    LaningDamageEvent(**{**_pick(e, LaningDamageEvent), "inflictor": _inflictor_key(e.get("inflictor"))})
                    for e in _dicts(p.get("laning_damage_events"))
                ],
                laning_regen_events=[
                    LaningRegenEvent(**{**_pick(r, LaningRegenEvent), "item": canonical_item_key(r.get("item"))})
                    for r in _dicts(p.get("laning_regen_events"))
                ],
            ))

        slot_to_player = {p.player_slot: p for p in players}

        smokes = []
        for s in _dicts(raw.get("smokes")):
            start = _as_int(s.get("time"))
            smoke_slots = s.get("player_slots", s.get("players", []))
            # Schema 3: the hero that used the smoke (before: the first hero it reached).
            user = _as_int(s.get("player_slot"), -1) if schema >= 3 and s.get("player_slot") is not None else -1
            smokes.append(SmokeEvent(
                time=start,
                team=s.get("team") if s.get("team") in ("radiant", "dire") else "radiant",
                player_slots=[_as_int(v) for v in smoke_slots] if isinstance(smoke_slots, list) else [],
                player_slot=user if user in slot_to_player else None,
                x=conv(s.get("x")),
                y=conv(s.get("y")),
                end_time=_as_int(s.get("end_time"), start),
                path=[[conv(pt[0]), conv(pt[1])] for pt in (s.get("path") or [])
                      if isinstance(pt, (list, tuple)) and len(pt) >= 2],
                result=str(s.get("result") or "unknown"),
                kills_gained=_as_int(s.get("kills_gained")),
                deaths_suffered=_as_int(s.get("deaths_suffered")),
                objective_taken=s.get("objective_taken") or None,
            ))

        teamfights = []
        death_windows: list[tuple[float, float]] = []
        analyzer_kill_targets = False
        for tf in _dicts(raw.get("teamfights")):
            tf_players = []
            for tp in _dicts(tf.get("players")):
                tp_slot = _as_int(tp.get("player_slot"))
                owner = slot_to_player.get(tp_slot)
                if owner is not None:
                    tf_hero_name, tf_hero_slug = owner.hero_name, owner.hero_slug
                else:
                    info = hero_lookup.get(normalize_hero_key(tp.get("hero_name")), {})
                    tf_hero_name = info.get("name", tp.get("hero_name", ""))
                    tf_hero_slug = info.get("slug", "")
                death_off = tp.get("death_time_offset")
                analyzer_kill_targets = analyzer_kill_targets or "kill_targets" in tp
                tf_players.append(TeamfightPlayer(
                    player_slot=tp_slot,
                    hero_name=tf_hero_name,
                    hero_slug=tf_hero_slug,
                    x=conv(tp.get("x")),
                    y=conv(tp.get("y")),
                    damage_dealt=_as_int(tp.get("damage_dealt")),
                    damage_taken=_as_int(tp.get("damage_taken")),
                    healing=_as_int(tp.get("healing")),
                    kills=_as_int(tp.get("kills")),
                    deaths=_as_int(tp.get("deaths")),
                    abilities_used=[str(a) for a in (tp.get("abilities_used") or [])],
                    gold_delta=_as_int(tp.get("gold_delta")),
                    xp_delta=_as_int(tp.get("xp_delta")),
                    item_uses={canonical_item_key(k): v for k, v in _int_dict(tp.get("item_uses")).items()},
                    buybacks=_as_int(tp.get("buybacks")),
                    death_time_offset=_as_float(death_off) if death_off is not None else None,
                    kill_targets=_kill_targets(tp.get("kill_targets"), name_by_slot, hero_names),
                    positions=[
                        PositionSnapshot(x=conv(ps.get("x")), y=conv(ps.get("y")),
                                         time_offset=_as_float(ps.get("time_offset")))
                        for ps in _dicts(tp.get("positions"))
                    ],
                    ability_casts=[
                        AbilityCast(
                            ability_name=ability_display_name(str(a.get("name") or "")) if a.get("name") else "",
                            ability_key=str(a.get("key") or a.get("name") or ""),
                            time_offset=_as_float(a.get("time_offset")),
                            x=conv(a.get("x")),
                            y=conv(a.get("y")),
                        )
                        for a in _dicts(tp.get("ability_casts"))
                    ],
                ))
            start = _as_int(tf.get("start", tf.get("start_time")))
            end = _as_int(tf.get("end", tf.get("end_time")))
            teamfights.append(TeamfightEvent(
                start_time=start,
                end_time=end,
                radiant_deaths=_as_int(tf.get("radiant_deaths")),
                dire_deaths=_as_int(tf.get("dire_deaths")),
                gold_delta=_as_int(tf.get("gold_delta")),
                xp_delta=_as_int(tf.get("xp_delta")),
                players=tf_players,
            ))
            # Schema 3 pads the window and reports the real death bounds.
            death_windows.append((_as_float(tf.get("first_death"), start), _as_float(tf.get("last_death"), end)))
        if kills_log and not analyzer_kill_targets:
            _apply_kills_to_teamfights(teamfights, death_windows, kills_log, name_by_slot)

        slot_by_hero = {normalize_hero_key(key): p.player_slot
                        for p in players for key in (p.hero_slug, p.hero_name) if key}
        objectives = [_normalize_clarity_objective(o, slot_by_hero) for o in _dicts(raw.get("objectives"))]
        objectives.sort(key=lambda o: _as_int(o.get("time")))
        buildings = _normalize_buildings(_dicts(raw.get("buildings")), conv)
        status = building_status_bitmasks(buildings, objectives)

        # null = the analyzer could not determine the winner (schema 3). Older
        # output always said false, which a truncated replay cannot know.
        radiant_win = raw.get("radiant_win")
        winner_known = isinstance(radiant_win, bool) and not (schema < 3 and partial)

        # Without file info (truncated replay) the id comes from the game rules;
        # an analyzer that could only decode 32 bits of it does not know the id.
        match_id = 0 if raw.get("match_id_source") == "game_rules_32bit" else _as_int(raw.get("match_id"))

        return MatchData(
            match_id=match_id,
            duration=duration,
            radiant_win=bool(radiant_win),
            game_mode=game_mode_code(raw.get("game_mode", 0)),
            start_time=_as_int(raw.get("start_time")),
            radiant_score=_as_int(raw.get("radiant_score")),
            dire_score=_as_int(raw.get("dire_score")),
            players=players,
            wards=sorted(all_wards, key=lambda w: w.time),
            smokes=sorted(smokes, key=lambda s: s.time),
            teamfights=teamfights,
            ability_events=sorted(all_ability_events, key=lambda e: e.time),
            gold_xp_timeline=_gold_xp_timeline(players),
            kills_log=kills_log,
            radiant_gold_adv=_per_minute(raw.get("radiant_gold_adv"), duration),
            radiant_xp_adv=_per_minute(raw.get("radiant_xp_adv"), duration),
            picks_bans=_clarity_picks_bans(raw, hero_lookup),
            objectives=objectives,
            chat=_dicts(raw.get("chat")),
            first_blood_time=_as_int(raw.get("first_blood_time")),
            cluster=_as_int(raw.get("cluster")),
            region=_as_int(raw.get("region")),
            patch=str(raw.get("patch") or ""),
            game_build=_as_int(raw.get("game_build")),
            talent_names_patch=talent_names_patch(),
            buildings=buildings,
            partial=partial,
            winner_known=winner_known,
            **status,
        )


def _denies_per_minute(snapshots: list[LaningSnapshot]) -> list[int]:
    """Denies at each full minute of the laning phase (0-10), from the 5 s snapshots."""
    series: list[int] = []
    for minute in range(11):
        mark = minute * 60
        nearest = min(snapshots, key=lambda s: abs(s.time - mark), default=None)
        if nearest is None or abs(nearest.time - mark) > 5:
            break
        series.append(nearest.denies)
    return series


def _position_log(value: Any) -> list[list[int]]:
    """Validated ``[time_s, x, y, hp_pct]`` samples (ints; hp_pct -1 = unknown)."""
    out: list[list[int]] = []
    for entry in value if isinstance(value, list) else []:
        if isinstance(entry, (list, tuple)) and len(entry) >= 3:
            hp = _as_int(entry[3], -1) if len(entry) > 3 else -1
            out.append([_as_int(entry[0]), _as_int(entry[1]), _as_int(entry[2]), hp])
    return out


# KillEvent.killer_team codes (analyzer ``kills_log[].killer_team``)
_UNIT_TEAMS = ("radiant", "dire", "neutral")


def _clarity_kills_log(value: Any, conv, slots: set[int]) -> list[KillEvent]:
    """Analyzer ``kills_log`` (schema 3) -> KillEvent list in time order."""
    kills: list[KillEvent] = []
    for k in _dicts(value):
        victim = _as_int(k.get("victim_slot"), -1)
        if victim not in slots:
            continue
        killer = _as_int(k.get("killer_slot"), -1) if k.get("killer_slot") is not None else -1
        killer_slot = killer if killer in slots else None
        unit = str(k.get("killer_unit") or "")
        if killer_slot is not None and unit.startswith("npc_dota_hero_"):
            unit = ""  # the killer hero itself; only summons and non-hero units are named
        assists = k.get("assist_slots") if isinstance(k.get("assist_slots"), list) else []
        kills.append(KillEvent(
            time=round(_as_float(k.get("time")), 1),
            victim_slot=victim,
            killer_slot=killer_slot,
            killer_unit=unit,
            # absent in output of analyzers before 1.4.0
            killer_team=k.get("killer_team") if k.get("killer_team") in _UNIT_TEAMS else None,
            x=conv(k["x"]) if k.get("x") is not None else None,
            y=conv(k["y"]) if k.get("y") is not None else None,
            assist_slots=[s for s in (_as_int(a, -1) for a in assists) if s in slots],
            # absent in output of analyzers before 1.5.0
            respawn_time=round(_as_float(k["respawn_time"]), 1) if k.get("respawn_time") is not None else None,
            deny=bool(k.get("deny", False)),
        ))
    kills.sort(key=lambda k: k.time)
    return kills


def _kill_targets(value: Any, name_by_slot: dict[int, str], hero_names: dict[str, str]) -> list[dict]:
    """Analyzer ``kill_targets`` -> ``[{target, target_slot, time_offset}]`` (contract shape)."""
    slot_by_name = {name: slot for slot, name in name_by_slot.items()}
    out: list[dict] = []
    for kt in _dicts(value):
        slot = _as_int(kt.get("target_slot"), -1) if kt.get("target_slot") is not None else -1
        name = name_by_slot.get(slot) or hero_names.get(normalize_hero_key(kt.get("target")), "")
        if slot not in name_by_slot:
            slot = slot_by_name.get(name, -1)
        if slot < 0:
            continue
        offset = kt.get("time_offset")
        out.append({"target": name, "target_slot": slot,
                    "time_offset": _as_float(offset) if offset is not None else None})
    return out


def _apply_kills_to_teamfights(teamfights: list[TeamfightEvent], death_windows: list[tuple[float, float]],
                               kills: list[KillEvent], name_by_slot: dict[int, str]) -> None:
    """Fill ``kill_targets`` and missing ``death_time_offset`` values from the kill log.

    ``death_windows[i]`` is the (first death, last death) time of ``teamfights[i]``;
    padded fight windows may overlap, the death windows do not.
    """
    for tf, (first, last) in zip(teamfights, death_windows):
        by_slot = {tp.player_slot: tp for tp in tf.players}
        for k in kills:  # time-ordered: the first death of a player sets the offset
            if not first - 1 <= k.time <= last + 1:
                continue
            offset = max(0.0, round(k.time - tf.start_time, 1))
            victim = by_slot.get(k.victim_slot)
            if victim is not None and victim.death_time_offset is None:
                victim.death_time_offset = offset
            killer = by_slot.get(k.killer_slot) if k.killer_slot is not None else None
            if killer is not None and not k.deny:
                killer.kill_targets.append({
                    "target": name_by_slot.get(k.victim_slot, ""),
                    "target_slot": k.victim_slot,
                    "time_offset": offset,
                })


def _clarity_picks_bans(raw: dict, hero_lookup: dict[str, dict]) -> list[dict]:
    """Draft entries with a real ``hero_id`` and ``team`` 0/1/None."""
    entries = _dicts(raw.get("picks_bans"))
    # Analyzer output before schema 3 alternated the team of all-pick bans (a
    # guess); that fallback draft is recognisable by the hero_name on its picks.
    guessed_bans = "draft_source" not in raw and any(e.get("is_pick") and e.get("hero_name") for e in entries)
    out: list[dict] = []
    for entry in entries:
        entry = dict(entry)
        entry["is_pick"] = bool(entry.get("is_pick"))
        hero_id = _as_int(entry.get("hero_id"))
        if not hero_id and entry.get("hero_name"):
            hero_id = hero_lookup.get(normalize_hero_key(entry["hero_name"]), {}).get("id", 0)
        entry["hero_id"] = hero_id
        team = entry.get("team")
        if team not in (0, 1) or isinstance(team, bool) or (guessed_bans and not entry["is_pick"]):
            team = None
        entry["team"] = team
        entry["order"] = _as_int(entry.get("order"))
        out.append(entry)
    return out


def _pick(data: dict, model: type) -> dict:
    """Keep only the fields a pydantic model declares (ignores extra/unknown keys)."""
    fields = model.model_fields
    out: dict[str, Any] = {}
    for key, value in data.items():
        if key not in fields or value is None:
            continue
        annotation = fields[key].annotation
        if annotation is int:
            value = _as_int(value)
        elif annotation is float:
            value = _as_float(value)
        elif annotation is str:
            value = str(value)
        out[key] = value
    return out


def _normalize_clarity_objective(obj: dict, slot_by_hero: dict[str, int] | None = None) -> dict:
    """Map analyzer objective events onto the OpenDota-style shape consumers expect.

    ``slot_by_hero`` (normalized hero key -> player_slot) resolves the victim of
    a first blood that older analyzer output only names by hero.
    """
    otype = str(obj.get("type") or "")
    out: dict[str, Any] = {"time": _as_int(obj.get("time"))}
    if obj.get("player_slot") is not None:
        out["player_slot"] = _as_int(obj.get("player_slot"))
    if otype in ("tower_kill", "barracks_kill", "ancient_kill", "building_kill"):
        # Schema 3 names the building entity that died (with the side of a
        # tier-4 tower); the combat-log unit name in "key" has no side.
        key = str(obj.get("building") or obj.get("key") or "")
        if key and not key.startswith("npc_dota_"):
            key = "npc_dota_" + key
        parsed = parse_building_name(key)
        out["type"] = "building_kill"
        out["key"] = key
        if parsed:
            # J8: the destroyed building's own name decides the teams.
            out["building_team"] = parsed["team"]
            out["team"] = "dire" if parsed["team"] == "radiant" else "radiant"
        elif obj.get("team") in ("radiant", "dire"):
            out["team"] = obj["team"]
        if obj.get("denied"):
            out["denied"] = True
        return out
    if otype == "CHAT_MESSAGE_FIRSTBLOOD":
        # Contract: player_slot = killer, key = the victim's player_slot as a string.
        out["type"] = otype
        slots = set((slot_by_hero or {}).values())
        victim = obj.get("victim_slot")
        if victim is None:
            raw_key = str(obj.get("key") or "")
            if raw_key.isdigit() and int(raw_key) in slots:
                victim = int(raw_key)
            else:
                victim = (slot_by_hero or {}).get(normalize_hero_key(raw_key))
        if victim is not None:
            out["key"] = str(_as_int(victim))
        if obj.get("slot") is not None:
            out["slot"] = obj["slot"]
        return out
    if otype == "roshan_kill":
        out["type"] = "CHAT_MESSAGE_ROSHAN_KILL"
    else:
        out["type"] = otype
    for key in ("team", "key", "slot", "value"):
        if obj.get(key) is not None:
            out[key] = obj[key]
    return out


def _annotate_building_objective(obj: dict) -> dict:
    """Add ``building_team`` / ``team`` (the side that took it) to a building kill.

    OpenDota's building_kill entries carry the killer in ``unit`` and the
    building in ``key`` but no team; derive both from the building's name.
    """
    if obj.get("type") != "building_kill":
        return obj
    parsed = parse_building_name(str(obj.get("key") or ""))
    if not parsed:
        return obj
    out = dict(obj)
    out.setdefault("building_team", parsed["team"])
    if out.get("team") not in ("radiant", "dire"):
        out["team"] = "dire" if parsed["team"] == "radiant" else "radiant"
    return out


def _normalize_buildings(raw_buildings: list[dict], conv) -> list[dict]:
    """Canonical building list (contract shape), names inferred from position if needed."""
    out: list[dict] = []
    ancient_seen: dict[str, int] = {"radiant": 0, "dire": 0}
    for b in raw_buildings:
        x, y = conv(b.get("x")), conv(b.get("y"))
        btype = b.get("type") if b.get("type") in ("tower", "barracks", "fort") else "other"
        parsed = parse_building_name(b.get("name"))
        team = b.get("team") if b.get("team") in ("radiant", "dire") else (parsed or {}).get("team")
        if team not in ("radiant", "dire"):
            team = "radiant" if x + y < 0 else "dire"
        name = str(b.get("name") or "")
        if parsed:
            key = parsed["key"]
            btype = parsed["type"]
            if key == "ancient":
                # Tier-4 tower without side: decide by the nearest default position.
                near = _nearest_tower_key(team, x, y, max_dist=900.0)
                if near in ("ancient_top", "ancient_bot"):
                    key = near
                else:
                    key = ("ancient_top", "ancient_bot")[min(ancient_seen[team], 1)]
                    ancient_seen[team] += 1
            name = _canonical_building_name(parsed["team"], btype, key)
        elif btype == "tower":
            near = _nearest_tower_key(team, x, y)
            if near:
                name = _canonical_building_name(team, "tower", near)
        elif btype == "barracks":
            near = _nearest_barracks_key(team, x, y)
            if near:
                name = _canonical_building_name(team, "barracks", near)
        elif btype == "fort":
            name = _canonical_building_name(team, "fort", "fort")
        destroyed = b.get("destroyed_time")
        out.append({
            "name": name,
            "team": team,
            "type": btype,
            "x": x,
            "y": y,
            "destroyed_time": _as_int(destroyed) if destroyed is not None else None,
        })
    return out


def _gold_xp_timeline(players: list[PlayerData]) -> list[GoldXpSnapshot]:
    """Team gold/xp per minute from the per-player gold_t / xp_t timelines."""
    radiant = [p for p in players if p.team == "radiant"]
    dire = [p for p in players if p.team == "dire"]
    if not radiant or not dire:
        return []
    min_len = min(len(p.gold_t) for p in radiant + dire)
    timeline: list[GoldXpSnapshot] = []
    for minute in range(min_len):
        timeline.append(GoldXpSnapshot(
            time=minute * 60,
            radiant_gold=sum(p.gold_t[minute] for p in radiant),
            dire_gold=sum(p.gold_t[minute] for p in dire),
            radiant_xp=sum(p.xp_t[minute] for p in radiant if len(p.xp_t) > minute),
            dire_xp=sum(p.xp_t[minute] for p in dire if len(p.xp_t) > minute),
        ))
    return timeline


