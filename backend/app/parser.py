# path -> (mtime, data, last mtime check); the mtime is re-checked at most every few seconds
_json_cache: dict[Path, tuple[float, dict, float]] = {}
_json_cache_lock = threading.Lock()
_JSON_RECHECK_S = 5.0


def _load_static_json(path: Path) -> dict:
    """Load a static JSON file (re-read only when its mtime changes)."""
    now = time.monotonic()
    with _json_cache_lock:
        cached = _json_cache.get(path)
        if cached is not None and now - cached[2] < _JSON_RECHECK_S:
            return cached[1]
    try:
        mtime = path.stat().st_mtime
    except OSError:
        return {}
    if cached is not None and cached[0] == mtime:
        with _json_cache_lock:
            _json_cache[path] = (mtime, cached[1], now)
        return cached[1]
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError) as exc:
        logger.warning("Failed to load static data %s: %s", path.name, exc)
        return {}
    if not isinstance(data, dict):
        data = {}
    with _json_cache_lock:
        _json_cache[path] = (mtime, data, now)
    return data


def load_hero_map() -> dict[int, dict]:
    """Load hero id -> {name, slug} map from static data."""
    result: dict[int, dict] = {}
    for hid, info in (_load_static_json(HEROES_JSON_PATH).get("by_id") or {}).items():
        if not isinstance(info, dict):
            continue
        try:
            result[int(hid)] = {"name": info.get("name", ""), "slug": info.get("slug", "")}
        except (TypeError, ValueError):
            continue
    return result


def hero_names(hero_id: Any) -> tuple[str, str]:
    """A hero's display name in English and in Simplified Chinese, by hero
    id. The Chinese one is the English one where the catalog has none; both
    are "" for an id it does not know."""
    try:
        info = (_load_static_json(HEROES_JSON_PATH).get("by_id") or {}).get(str(int(hero_id)))
    except (TypeError, ValueError):
        return "", ""
    name = str(info.get("name") or "") if isinstance(info, dict) else ""
    return name, str(info.get("name_zh") or name) if name else ""


def chat_wheel_entry(key: Any) -> dict | None:
    """Catalog entry of a chat-wheel message, by its chat key
    ("chatwheel_71") or message id: ``{"en", "zh"[, "sound"]}`` for a line —
    ``sound`` marks one that is also heard, and the two lines about a hero
    name it as ``{hero}`` ("{hero} is missing!") —, ``{"spray": True}`` for
    a spray. None for an id the catalog does not have.
    """
    text = str(key if key is not None else "")
    if text.startswith("chatwheel_"):
        text = text[len("chatwheel_"):]
    if not (text.isascii() and text.isdigit()):
        return None
    entry = (_load_static_json(CHAT_WHEEL_JSON_PATH).get("by_id") or {}).get(str(int(text)))
    return entry if isinstance(entry, dict) else None


def normalize_hero_key(name: str | None) -> str:
    """Normalize a hero identifier for matching.

    Accepts display names ("Queen of Pain"), heroes.json slugs ("queenofpain"),
    npc names ("npc_dota_hero_queenofpain") and entity-class conversions
    ("queen_of_pain"); all map to "queenofpain".
    """
    n = (name or "").strip().lower()
    if n.startswith("npc_dota_hero_"):
        n = n[len("npc_dota_hero_"):]
    return re.sub(r"[^a-z0-9]", "", n)


def _hero_lookup() -> dict[str, dict]:
    """normalized slug / display name -> {id, name, slug}."""
    lookup: dict[str, dict] = {}
    for hid, info in load_hero_map().items():
        entry = {"id": hid, "name": info.get("name") or info.get("slug") or "", "slug": info.get("slug") or ""}
        for key in (info.get("slug"), info.get("name")):
            norm = normalize_hero_key(key)
            if norm:
                lookup.setdefault(norm, entry)
    return lookup


def _items_by_key() -> dict[str, dict]:
    data = _load_static_json(ITEMS_JSON_PATH).get("by_key") or {}
    return data if isinstance(data, dict) else {}


def _item_id_map() -> dict[int, tuple[str, str]]:
    """item id -> (display name, key)."""
    result: dict[int, tuple[str, str]] = {}
    for key, info in _items_by_key().items():
        if isinstance(info, dict) and isinstance(info.get("id"), int):
            result[info["id"]] = (info.get("name") or key, info.get("key") or key)
    return result


def _data_layer(function: str):
    """A function of the data layer (``ai.data_manager``), or None without it.

    The parser works on the bundled catalogs alone; the data layer adds what
    was fetched since they were generated.
    """
    try:
        from .ai import data_manager
    except ImportError:
        return None
    return getattr(data_manager, function, None)


def item_display_name(key: str) -> str:
    """Display name for an item key (falls back to a title-cased key).

    The data layer names the item when it knows it: fetched game data first
    (an item added after the bundled catalog was generated), then the catalog.
    """
    resolve = _data_layer("resolve_item_name")
    name = resolve(key) if resolve is not None and key else None
    if name:
        return name
    info = _items_by_key().get(key)
    if isinstance(info, dict) and info.get("name"):
        return info["name"]
    return key.replace("_", " ").title()


