# (items.json by_key dict, squashed display name -> key) for the dict it was built from
_item_name_index_cache: tuple[dict, dict[str, str]] | None = None


def _squash(text: str) -> str:
    return re.sub(r"[^a-z0-9]", "", text.lower())


def _item_name_index() -> dict[str, str]:
    """Squashed display name ("bootsoftravel") -> item key, from items.json."""
    global _item_name_index_cache
    items = _items_by_key()
    cached = _item_name_index_cache
    if cached is not None and cached[0] is items:
        return cached[1]
    index: dict[str, str] = {}
    for key, info in items.items():
        if isinstance(info, dict) and info.get("name"):
            index.setdefault(_squash(str(info["name"])), key)
    _item_name_index_cache = (items, index)
    return index


def canonical_item_key(key: Any) -> str:
    """Item key in the OpenDota items.json form (no ``item_`` prefix).

    Analyzer keys normally are canonical already. Entity class-name leftovers
    ("boots_of_travel", "dustof_appearance") are mapped to the real key. A key
    that cannot be matched is returned unchanged, never dropped.
    """
    k = str(key or "").strip()
    if k.startswith("item_"):
        k = k[len("item_"):]
    if not k or k in _items_by_key():
        return k
    if k in _ITEM_KEY_ALIASES:
        return _ITEM_KEY_ALIASES[k]
    if k.startswith("recipe_"):
        return "recipe_" + canonical_item_key(k[len("recipe_"):])
    return _item_name_index().get(_squash(k), k)


def ability_display_name(key: str) -> str:
    """Display name for an ability key (falls back to the key itself).

    Talents ("special_bonus_*") are named by the data layer: it knows the
    current patch's talents from the fetched game data and takes the
    "{s:...}" template tokens out of their names, which OpenDota's catalogs
    leave unresolved. Every backend and the mock name a talent through here.
    """
    if key.startswith("special_bonus_"):
        data_layer_name = _data_layer("ability_display_name")
        if data_layer_name is not None:  # else: the static catalog below
            return data_layer_name(key) or key
    # Fetched game data first (an ability newer than the bundled catalog, a
    # renamed one), then the catalog; both through the data layer's index.
    resolve = _data_layer("resolve_ability_name")
    name = resolve(key) if resolve is not None and key else None
    if name:
        return name
    abilities = _load_static_json(ABILITIES_JSON_PATH).get("by_key") or {}
    info = abilities.get(key) if isinstance(abilities, dict) else None
    if isinstance(info, dict) and info.get("name"):
        return info["name"]
    return key


def _ability_id_map() -> dict[str, str]:
    """Ability id (as a string, like OpenDota's table) -> key, from the
    bundled catalog. Catalogs generated before 7.41f carry no ids: {} then.

    An entry has one ``id`` and, where the game lists several ids for the
    same ability (Templar Assassin's Hidden Gates: 3060 and 1617), all of
    them in ``ids``: every one maps to the key.
    """
    abilities = _load_static_json(ABILITIES_JSON_PATH).get("by_key") or {}
    result: dict[str, str] = {}
    for key, info in (abilities.items() if isinstance(abilities, dict) else ()):
        if not isinstance(info, dict):
            continue
        ids = info.get("ids") if isinstance(info.get("ids"), list) else []
        for ability_id in (info.get("id"), *ids):
            if isinstance(ability_id, int) and not isinstance(ability_id, bool):
                result.setdefault(str(ability_id), str(key))
    return result


