# The XP table and the skill-point schedules (before and since 7.40) are the
# game's rules: see ``game_constants``.
_XP_FOR_LEVEL = game_constants.XP_FOR_LEVEL
_POINT_LEVELS = game_constants.SKILL_POINT_LEVELS_BEFORE_TALENT_POINTS
_TALENT_LEVELS = game_constants.TALENT_LEVELS
_LAST_SKILL_POINT_LEVEL = game_constants.LAST_SKILL_POINT_LEVEL
# With fourteen of a hero's fifteen ability levels learned by level 14, the
# points of levels 15-17 can only go into the attribute bonus; the game
# spends them itself, and Valve's list has no entry for that. So the entry
# that completes the fifteen was made at level 18 (the third level of the
# ultimate), not at the level its place in the list suggests.
_BASIC_ABILITY_LEVELS = game_constants.BASIC_ABILITY_LEVELS
_ABILITY_LEVELS = game_constants.HERO_ABILITY_LEVELS
_LAST_ABILITY_LEVEL_AT = game_constants.LAST_ULTIMATE_LEVEL_AT
_SEPARATE_TALENTS_SINCE = game_constants.TALENT_POINTS_SINCE
_SEPARATE_TALENTS_RELEASED = game_constants.TALENT_POINTS_RELEASED
_PATCH_RE = re.compile(r"(\d+)\.(\d+)")


def talents_have_own_points(patch: str = "", start_time: int = 0) -> bool:
    """Whether a match follows the 7.40 skill rules (talents no longer cost a skill point).

    Decided by the game version when it is known ("7.41", "7.40b"), else by
    the start time, else True: the current rules.
    """
    version = _PATCH_RE.match(str(patch or "").strip())
    if version:
        return (int(version.group(1)), int(version.group(2))) >= _SEPARATE_TALENTS_SINCE
    if start_time and start_time > 0:
        return start_time >= _SEPARATE_TALENTS_RELEASED
    return True


def is_talent(key: str) -> bool:
    """A talent pick: any ``special_bonus_*`` key but the attribute bonus."""
    return key.startswith("special_bonus_") and key != "special_bonus_attributes"


# Game constants (dotaconstants files such as ``ability_ids``): downloaded
# once per process and name; a failed download is retried after
# _CONSTANTS_RETRY_S.
_constants: dict[str, Any] = {}
_constants_failed_at: dict[str, float] = {}
_constants_lock = threading.Lock()
_CONSTANTS_RETRY_S = 600


def reset_opendota_constants_cache() -> None:
    """Forget cached OpenDota constants (tests)."""
    with _constants_lock:
        _constants.clear()
        _constants_failed_at.clear()


def _upgrade_levels(keys: list[str], separate_talents: bool) -> list[int]:
    """Hero level at which each entry of a skill build was (at the earliest) made."""
    if not separate_talents:
        return [_POINT_LEVELS[min(i, len(_POINT_LEVELS) - 1)] for i in range(len(keys))]
    levels: list[int] = []
    talents = level = 0
    learned: Counter = Counter()
    for key in keys:
        if is_talent(key):
            levels.append(_TALENT_LEVELS[min(talents, len(_TALENT_LEVELS) - 1)])
            talents += 1
            continue
        level += 1
        if key != "special_bonus_attributes":
            learned[key] += 1
            # A level beyond the fourth (Invoker's orbs, Winter Wyvern's
            # Eldwurm's Edda) is not one of the fifteen.
            if (learned[key] <= _BASIC_ABILITY_LEVELS and len(learned) == 4
                    and sum(min(n, _BASIC_ABILITY_LEVELS) for n in learned.values()) == _ABILITY_LEVELS):
                level = max(level, _LAST_ABILITY_LEVEL_AT)
        levels.append(min(level, _LAST_SKILL_POINT_LEVEL))
    return levels


def _estimate_upgrade_times(keys: list[str], xp_t: list[int], separate_talents: bool = True,
                            duration: int = 0) -> list[int]:
    """Approximate when each entry of a skill build (ability keys in the order
    they were learned) was made, from the per-minute XP curve.

    OpenDota has the order but no times. Each entry is placed at the moment
    the hero reached the level that allowed it (see :func:`_upgrade_levels`;
    ``separate_talents`` = the rules since 7.40), never before the entry in
    front of it and never after the end of the match (*duration*, when
    known): a level reached after the last full minute of the curve was
    still reached in the game.
    """
    count = len(keys)
    end = float(duration) if duration and duration > 0 else None
    if not xp_t:
        return [int(min((i + 1) * 60, end)) if end is not None else (i + 1) * 60 for i in range(count)]
    level_time: dict[int, float] = {1: 0.0}
    for level in range(2, len(_XP_FOR_LEVEL) + 1):
        need = _XP_FOR_LEVEL[level - 1]
        for minute, xp in enumerate(xp_t):
            if xp >= need:
                if minute == 0:
                    level_time[level] = 0.0
                else:
                    prev = xp_t[minute - 1]
                    frac = (need - prev) / (xp - prev) if xp > prev else 1.0
                    level_time[level] = (minute - 1 + max(0.0, min(1.0, frac))) * 60
                break
    times: list[int] = []
    prev_t = 0.0
    for level in _upgrade_levels(keys, separate_talents):
        t = level_time.get(level)
        if t is None:
            t = prev_t + 60
        t = max(t, prev_t)
        if end is not None:
            t = min(t, end)
        times.append(int(t))
        prev_t = t
    return times


class OpenDotaParser(ReplayParser):
    """Fetch and parse match data from the OpenDota API."""

    API_BASE = "https://api.opendota.com/api"
    HEADERS = {"User-Agent": "DotaAnalyzer/1.0"}
    TIMEOUT_S = 30
    # Per source and constants file; a match request waits for these downloads.
    CONSTANTS_TIMEOUT_S = 10

    def name(self) -> str:
        return "opendota"

    def _url(self, path: str) -> str:
        url = f"{self.API_BASE}{path}"
        api_key = os.environ.get("OPENDOTA_API_KEY", "").strip()
        if api_key:
            url += ("&" if "?" in url else "?") + urllib.parse.urlencode({"api_key": api_key})
        return url

    def _request(self, path: str, method: str = "GET") -> Any:
        req = urllib.request.Request(self._url(path), method=method, headers=self.HEADERS)
        try:
            with urllib.request.urlopen(req, timeout=self.TIMEOUT_S) as resp:
                body = resp.read()
        except urllib.error.HTTPError as exc:
            status = exc.code
            logger.warning("OpenDota %s %s failed: HTTP %s", method, path, status)
            if status == 404:
                raise OpenDotaError("Match not found on OpenDota", status=404) from None
            if status == 429:
                raise OpenDotaError("OpenDota rate limit reached, please retry later", status=429) from None
            if status >= 500:
                raise OpenDotaError("OpenDota is temporarily unavailable", status=status) from None
            raise OpenDotaError(f"OpenDota request failed (HTTP {status})", status=status) from None
        except (urllib.error.URLError, http.client.HTTPException, TimeoutError, OSError) as exc:
            logger.warning("OpenDota %s %s failed: %s", method, path, exc)
            raise OpenDotaError("Could not reach OpenDota", status=None) from None
        try:
            return json.loads(body)
        except ValueError:
            logger.warning("OpenDota %s %s returned invalid JSON (%d bytes)", method, path, len(body))
            raise OpenDotaError("Invalid response from OpenDota", status=None) from None

    def _api_get(self, path: str) -> Any:
        return self._request(path, "GET")

    def _api_post(self, path: str) -> Any:
        return self._request(path, "POST")

    def request_parse(self, match_id: int) -> dict:
        """Request OpenDota to parse a match. Returns job info."""
        result = self._api_post(f"/request/{int(match_id)}")
        return result if isinstance(result, dict) else {}

    def _load_item_map(self) -> dict[int, tuple[str, str]]:
        """Load item id -> (name, key) map from static data."""
        return _item_id_map()

    def _download_constants(self, name: str) -> Any:
        """One game-constants file (``ability_ids``, ``item_ids``, ``patch``).

        From the sources of the data layer, in its order
        (``ai.data_manager.CONSTANTS_SOURCES``): the dotaconstants master
        branch, its mirror, then OpenDota's ``/constants`` API. The API comes
        last because it serves a release that can be months old and lacks the
        ids of newer items and abilities. Without the data layer only the API
        is asked. Blocking; raises when no source delivers.
        """
        download = _data_layer("download_constants")
        if download is None:
            return self._api_get(f"/constants/{name}")
        return download(name, timeout=self.CONSTANTS_TIMEOUT_S)

    def _load_constants(self, name: str) -> Any:
        """A game-constants file (cached for the process; retried after failures).

        Returns None when the constants are unavailable; callers degrade
        (raw ids instead of names) instead of failing the parse.
        """
        with _constants_lock:
            if name in _constants:
                return _constants[name]
            failed_at = _constants_failed_at.get(name)
            if failed_at is not None and time.monotonic() - failed_at < _CONSTANTS_RETRY_S:
                return None
        try:
            data = self._download_constants(name)
        except Exception as exc:  # any source error: the parse goes on without the table
            logger.warning("Game constants '%s' unavailable: %s", name, exc)
            data = None
        with _constants_lock:
            if isinstance(data, (dict, list)) and data:
                _constants[name] = data
                _constants_failed_at.pop(name, None)
                return data
            _constants_failed_at[name] = time.monotonic()
            return None

    def _load_ability_ids(self) -> dict[str, str]:
        """Ability id -> ability key: the downloaded table (current) over the
        ids of the bundled catalog."""
        data = self._load_constants("ability_ids")
        fetched = {str(k): str(v) for k, v in data.items()} if isinstance(data, dict) else {}
        return {**_ability_id_map(), **fetched}

    def _load_item_ids(self) -> dict[str, str]:
        """OpenDota item id -> item key (for ids the static catalog does not list)."""
        data = self._load_constants("item_ids")
        return {str(k): str(v) for k, v in data.items()} if isinstance(data, dict) else {}

    def _load_patches(self) -> list[dict]:
        """OpenDota patch table: ``[{"id": 60, "name": "7.41", "date": ...}]``."""
        return _dicts(self._load_constants("patch"))

    @staticmethod
    def _inventory_ids(p: dict) -> list[int]:
        keys = [f"item_{i}" for i in range(6)] + [f"backpack_{i}" for i in range(3)] + ["item_neutral"]
        return [iid for iid in (_as_int(p.get(k)) for k in keys) if iid]

    async def parse(self, match_id_str: str) -> MatchData:
        try:
            match_id = int(str(match_id_str).strip())
        except ValueError:
            raise OpenDotaError("Invalid match ID", status=400) from None
        if match_id <= 0:
            raise OpenDotaError("Invalid match ID", status=400)
        # Blocking urllib calls run in worker threads (keeps the event loop free).
        raw = await asyncio.to_thread(self._api_get, f"/matches/{match_id}")
        if not isinstance(raw, dict) or ("error" in raw and not raw.get("players")):
            raise OpenDotaError("Match not found on OpenDota", status=404)
        raw_players = _dicts(raw.get("players"))
        # A constants table is downloaded only for what the bundled catalogs
        # and the stored game data do not tell: an ability or item id newer
        # than the catalog, a start time the stored patch table cannot name.
        ability_ids = _ability_id_map()
        item_map = self._load_item_map()
        loaders: dict[str, Any] = {}
        if any(str(ab_id) not in ability_ids for p in raw_players
               for ab_id in (p.get("ability_upgrades_arr") or []) if ab_id is not None):
            loaders["ability_ids"] = self._load_ability_ids
        if any(iid not in item_map for p in raw_players for iid in self._inventory_ids(p)):
            loaders["item_ids"] = self._load_item_ids
        if raw.get("patch") is not None and not _stored_patch(_as_int(raw.get("start_time"))):
            loaders["patches"] = self._load_patches
        # Side by side: a source that times out is waited for once, not once per table.
        tables = dict(zip(loaders, await asyncio.gather(*(asyncio.to_thread(load) for load in loaders.values()))))
        return await asyncio.to_thread(
            self._transform, raw, load_hero_map(), item_map, tables.get("ability_ids", ability_ids),
            tables.get("item_ids", {}), tables.get("patches", []))

    @staticmethod
    def _lane_fields(p: dict, team: str) -> tuple[int, int, bool]:
        """(lane, lane_role, is_roaming) per the shared contract.

        OpenDota lane: 1=bot, 2=mid, 3=top, 4=radiant jungle, 5=dire jungle.
        Both jungles become 4; lane_role is derived from lane when missing.
        """
        lane = _as_int(p.get("lane"))
        if lane == 5:
            lane = 4
        if lane not in (0, 1, 2, 3, 4):
            lane = 0
        lane_role = _as_int(p.get("lane_role"))
        if lane_role not in (0, 1, 2, 3, 4):
            lane_role = 0
        if lane and not lane_role:
            lane_role = _LANE_ROLE[team][lane]
        if lane_role and not lane:
            inverse = {v: k for k, v in _LANE_ROLE[team].items()}
            lane = inverse.get(lane_role, 0)
        return lane, lane_role, bool(p.get("is_roaming", False))

    @staticmethod
    def _ward_cell(w: dict) -> tuple[float, float] | None:
        """Ward position in OpenDota cells: x/y, or the "[x, y]" ``key`` of older logs."""
        key = w.get("key")
        if isinstance(key, str):
            try:
                key = json.loads(key)
            except ValueError:
                key = None
        key = key if isinstance(key, (list, tuple)) and len(key) >= 2 else (None, None)
        cell = []
        for value, fallback in ((w.get("x"), key[0]), (w.get("y"), key[1])):
            for candidate in (value, fallback):
                try:
                    number = float(candidate)
                except (TypeError, ValueError):
                    continue
                if math.isfinite(number):
                    cell.append(number)
                    break
        return (cell[0], cell[1]) if len(cell) == 2 else None

    @classmethod
    def _ward_events(cls, p: dict, slot: int, team: str, hero_teams: dict[str, str] | None = None,
                     duration: int = 0, hero_slots: dict[str, int] | None = None) -> list[WardEvent]:
        """Ward placements with world coordinates, destruction times and the deward / deny flags.

        ``hero_teams`` (normalized hero key -> team) tells whether the unit that
        removed a ward was an enemy or an ally, ``hero_slots`` (-> player_slot)
        which hero it was. An entry without a position is skipped.
        """
        hero_teams = hero_teams or {}
        wards: list[WardEvent] = []
        for log_key, left_key, ward_type in (("obs_log", "obs_left_log", "observer"),
                                             ("sen_log", "sen_left_log", "sentry")):
            left_entries = _dicts(p.get(left_key))
            by_handle = {w["ehandle"]: w for w in left_entries if w.get("ehandle")}
            by_pos: dict[tuple, list[dict]] = {}
            for w in left_entries:
                cell = cls._ward_cell(w)
                if not w.get("ehandle") and cell:
                    by_pos.setdefault((round(cell[0], 1), round(cell[1], 1)), []).append(w)
            for w in _dicts(p.get(log_key)):
                cell = cls._ward_cell(w)
                if cell is None:
                    logger.debug("Skipping OpenDota %s entry without a position", log_key)
                    continue
                placed = _as_int(w.get("time"))
                left = None
                ehandle = w.get("ehandle")
                if ehandle and ehandle in by_handle:
                    left = by_handle[ehandle]
                else:
                    pos_key = (round(cell[0], 1), round(cell[1], 1))
                    candidates = sorted((c for c in by_pos.get(pos_key, []) if _as_int(c.get("time")) >= placed),
                                        key=lambda c: _as_int(c.get("time")))
                    if candidates:
                        left = candidates[0]
                        by_pos[pos_key].remove(left)
                destroyed = _as_int(left.get("time")) if left is not None else None
                if destroyed is not None and duration > 0 and destroyed > duration:
                    destroyed = None  # expired in the post-game: alive at game end
                dewarded = destroyed is not None and cls._dewarded(
                    left or {}, team, ward_type, placed, destroyed, hero_teams)
                denied = destroyed is not None and not dewarded and cls._denied(
                    left or {}, team, ward_type, placed, destroyed, hero_teams)
                attacker = normalize_hero_key((left or {}).get("attackername"))
                killer = (hero_slots or {}).get(attacker) if dewarded or denied else None
                wards.append(WardEvent(
                    ward_type=ward_type,
                    x=geo.opendota_cell_to_world(cell[0]),
                    y=geo.opendota_cell_to_world(cell[1]),
                    time=placed,
                    player_slot=slot,
                    destroyed_time=destroyed,
                    team=team,
                    dewarded=dewarded,
                    denied=denied,
                    killer_slot=killer,
                ))
        return sorted(wards, key=lambda w: w.time)

    @staticmethod
    def _dewarded(left: dict, ward_team: str, ward_type: str, placed: int, destroyed: int,
                  hero_teams: dict[str, str]) -> bool:
        """Whether an enemy removed the ward, from the left-log ``attackername``.

        A ward that expires is "killed" by its owner; an enemy hero or lane
        unit means a deward. Without a usable attacker the lifetime decides.
        """
        attacker = str(left.get("attackername") or "")
        attacker_team = hero_teams.get(normalize_hero_key(attacker)) if attacker else None
        if attacker_team is None and "goodguys" in attacker:
            attacker_team = "radiant"
        elif attacker_team is None and "badguys" in attacker:
            attacker_team = "dire"
        if attacker_team is None:
            return _dewarded_by_lifetime(ward_type, placed, destroyed)
        return attacker_team != ward_team

    @staticmethod
    def _denied(left: dict, ward_team: str, ward_type: str, placed: int, destroyed: int,
                hero_teams: dict[str, str]) -> bool:
        """Whether a hero of the ward's own side destroyed it before its time.

        The left log names the owner for a ward that ran out and the
        attacking hero (the owner included) for one that was denied: only
        the lifetime tells the two apart.
        """
        attacker_team = hero_teams.get(normalize_hero_key(left.get("attackername")))
        return attacker_team == ward_team and _ward_fell_early(ward_type, placed, destroyed)

    def _transform(self, raw: dict, hero_map: dict, item_map: dict,
                   ability_ids: dict[str, str] | None = None,
                   item_ids: dict[str, str] | None = None,
                   patches: list[dict] | None = None) -> MatchData:
        """OpenDota match JSON -> MatchData.

        ``ability_ids`` / ``item_ids`` / ``patches`` are OpenDota constants
        (id -> key, patch table); without them raw ids are kept and the patch
        stays empty.
        """
        ability_ids = ability_ids or {}
        item_ids = item_ids or {}
        raw_players = _dicts(raw.get("players"))
        duration = _as_int(raw.get("duration"))
        start_time = _as_int(raw.get("start_time"))
        patch = _match_patch(raw.get("patch"), patches or [], start_time)
        separate_talents = talents_have_own_points(patch, start_time)
        players: list[PlayerData] = []
        all_wards: list[WardEvent] = []

        # Heroes first: unit-keyed dicts and logs of every player refer to them.
        slots = [_as_int(p.get("player_slot"), idx if idx < 5 else 128 + idx - 5)
                 for idx, p in enumerate(raw_players)]
        heroes: list[tuple[int, str, str]] = []
        for idx, p in enumerate(raw_players):
            hero_id = _as_int(p.get("hero_id"))
            info = hero_map.get(hero_id, {})
            heroes.append((hero_id, info.get("name") or (f"hero_{hero_id}" if hero_id else f"unknown_{idx}"),
                           info.get("slug", "")))
        hero_names = _hero_name_index((name, slug) for _id, name, slug in heroes)
        name_by_slot = {slot: name for slot, (_id, name, _slug) in zip(slots, heroes)}
        slot_by_hero = {normalize_hero_key(key): slot
                        for slot, (_id, name, slug) in zip(slots, heroes) for key in (slug, name) if key}
        hero_teams = {key: _team_for_slot(slot) for key, slot in slot_by_hero.items()}

        # Team scores. Matches from before Valve's API had them (2013) come
        # with 0 : 0 beside a full scoreboard: the kills of each side's
        # players are the score then.
        scores = {team: _as_int(raw.get(f"{team}_score")) for team in ("radiant", "dire")}
        if not any(scores.values()):
            for slot, p in zip(slots, raw_players):
                scores[_team_for_slot(slot)] += _as_int(p.get("kills"))

        def _item(item_id: int) -> tuple[str, str]:
            """(display name, key) of an inventory item id; never dropped."""
            if item_id in item_map:
                return item_map[item_id]
            key = item_ids.get(str(item_id))
            # Not in the static catalog: the OpenDota key, else a stable placeholder code.
            key = canonical_item_key(key) if key else f"item_{item_id}"
            return item_display_name(key), key

        for idx, p in enumerate(raw_players):
            slot = slots[idx]
            team = _team_for_slot(slot)
            hero_id, hero_name, hero_slug = heroes[idx]

            # Purchases keep the time OpenDota logged. Its log has no rows for
            # strategy-time purchases on current builds, so the starting items
            # (time <= 0) can be incomplete; a purchase after the horn is never
            # presented as one.
            items = [
                ItemEvent(
                    item_name=item_display_name(str(e.get("key") or "")),
                    time=_as_int(e.get("time")),
                    item_key=str(e.get("key") or ""),
                    charges=_as_int(e["charges"]) if e.get("charges") is not None else None,
                )
                for e in _dicts(p.get("purchase_log")) if e.get("key")
            ]
            items.sort(key=lambda it: it.time)

            final = [_item(iid) for iid in (_as_int(p.get(f"item_{i}")) for i in range(6)) if iid]
            backpack = [_item(iid)[1] for iid in (_as_int(p.get(f"backpack_{i}")) for i in range(3)) if iid]
            neutral_id = _as_int(p.get("item_neutral"))
            neutral_item = _item(neutral_id)[1] if neutral_id else ""

            # Skill build: ability ids -> keys via the id table, times from the XP curve
            ability_arr = [a for a in (p.get("ability_upgrades_arr") or []) if a is not None]
            ability_keys = [ability_ids.get(str(ab_id)) or f"ability_{ab_id}" for ab_id in ability_arr]
            xp_t = _per_minute(p.get("xp_t"), duration)
            upgrade_times = _estimate_upgrade_times(ability_keys, xp_t, separate_talents, duration)
            skills: list[SkillEvent] = []
            levels: Counter = Counter()
            for i, ab_id in enumerate(ability_arr):
                key = ability_keys[i]
                levels[key] += 1
                skills.append(SkillEvent(
                    ability_name=ability_display_name(key),
                    ability_key=key if str(ab_id) in ability_ids else str(ab_id),
                    level=levels[key],
                    time=upgrade_times[i],
                ))

            wards = self._ward_events(p, slot, team, hero_teams, duration, slot_by_hero)
            all_wards.extend(wards)
            kills, assists = _as_int(p.get("kills")), _as_int(p.get("assists"))
            participation = _as_float(p.get("teamfight_participation")) if p.get("teamfight_participation") is not None else None
            # Not a parsed match: no value, or (first player of old matches) a
            # 0 that the hero's own kills and assists contradict.
            if participation is None or (participation <= 0 and kills + assists > 0):
                participation = kill_participation(kills, assists, scores[team])
            buyback_log = _time_log(p.get("buyback_log"))
            lane, lane_role, is_roaming = self._lane_fields(p, team)
            gold_t = _per_minute(p.get("gold_t"), duration)
            lane_eff = _as_float(p.get("lane_efficiency"))
            lane_eff_pct = _as_float(p.get("lane_efficiency_pct"))
            if not lane_eff:
                lane_eff, lane_eff_pct = lane_efficiency(gold_t)

            players.append(PlayerData(
                player_slot=slot,
                hero_id=hero_id,
                hero_name=hero_name,
                hero_slug=hero_slug,
                player_name=str(p.get("personaname") or p.get("name") or ""),
                team=team,
                kills=kills,
                deaths=_as_int(p.get("deaths")),
                assists=assists,
                level=max(1, _as_int(p.get("level"), 1)),
                last_hits=_as_int(p.get("last_hits")),
                denies=_as_int(p.get("denies")),
                gold_per_min=_as_int(p.get("gold_per_min")),
                xp_per_min=_as_int(p.get("xp_per_min")),
                hero_damage=_as_int(p.get("hero_damage")),
                tower_damage=_as_int(p.get("tower_damage")),
                hero_healing=_as_int(p.get("hero_healing")),
                net_worth=_as_int(p.get("net_worth")) or _as_int(p.get("total_gold")),
                items=items,
                backpack=backpack,
                final_items=[name for name, _key in final],
                final_item_keys=[key for _name, key in final],
                neutral_item=neutral_item,
                skills=skills,
                wards=wards,
                ability_events=[],
                gold_t=gold_t,
                xp_t=xp_t,
                lh_t=_per_minute(p.get("lh_t"), duration),
                dn_t=_per_minute(p.get("dn_t"), duration),
                lane=lane,
                lane_role=lane_role,
                is_roaming=is_roaming,
                lane_efficiency=lane_eff,
                lane_efficiency_pct=lane_eff_pct,
                # OpenDota lists every unit here; the contract keeps the heroes.
                killed=_unit_keyed(p.get("killed"), hero_names, heroes_only=True),
                killed_by=_unit_keyed(p.get("killed_by"), hero_names, heroes_only=True),
                # ... and counts what a hero did to itself (Soul Ring, Blood Grenade).
                damage=_without(_unit_keyed(p.get("damage"), hero_names), hero_name),
                damage_taken=_without(_unit_keyed(p.get("damage_taken"), hero_names), hero_name),
                damage_inflictor=_inflictor_dict(p.get("damage_inflictor")),
                gold_reasons=_int_dict(p.get("gold_reasons")),
                xp_reasons=_int_dict(p.get("xp_reasons")),
                benchmarks=p.get("benchmarks") if isinstance(p.get("benchmarks"), dict) else {},
                runes_log=_dicts(p.get("runes_log")),
                runes=_int_dict(p.get("runes")),
                stuns=_as_float(p.get("stuns")),
                actions_per_min=_as_int(p.get("actions_per_min")),
                teamfight_participation=participation,
                buyback_count=len(buyback_log) or _as_int(p.get("buyback_count")),
                buyback_log=buyback_log,
                # The ward logs are the wards; the summary counters stand in
                # when a match has no logs (and can be off by one when it has).
                obs_placed=(sum(1 for w in wards if w.ward_type == "observer")
                            if isinstance(p.get("obs_log"), list) else _as_int(p.get("obs_placed"))),
                sen_placed=(sum(1 for w in wards if w.ward_type == "sentry")
                            if isinstance(p.get("sen_log"), list) else _as_int(p.get("sen_placed"))),
                observer_kills=_as_int(p.get("observer_kills")),
                sentry_kills=_as_int(p.get("sentry_kills")),
                lane_kills=_lane_kills(p, team),
                neutral_kills=_as_int(p.get("neutral_kills")),
                ancient_kills=_as_int(p.get("ancient_kills")),
                tower_kills=_as_int(p.get("tower_kills")),
                roshans_killed=_as_int(p.get("roshan_kills", p.get("roshans_killed"))),
                courier_kills=_as_int(p.get("courier_kills")),
                multi_kills=_int_dict(p.get("multi_kills")),
                kill_streaks=_int_dict(p.get("kill_streaks")),
                purchase_log=[
                    {"time": it.time, "key": it.item_key, **({} if it.charges is None else {"charges": it.charges})}
                    for it in items
                ],
                lane_pos=p.get("lane_pos") if isinstance(p.get("lane_pos"), dict) else {},
            ))

        # Ward kills are the enemy wards a hero removed, as the replay parser
        # counts them (OpenDota's counters include a deny of an own ward). The
        # left logs say who removed each ward; without them the counters stay.
        if any(e.get("attackername") for p in raw_players
               for key in ("obs_left_log", "sen_left_log") for e in _dicts(p.get(key))):
            dewards = Counter((w.killer_slot, w.ward_type) for w in all_wards
                              if w.dewarded and w.killer_slot is not None)
            for player in players:
                player.observer_kills = dewards[(player.player_slot, "observer")]
                player.sentry_kills = dewards[(player.player_slot, "sentry")]

        kills_log, reincarnations, uncounted = _opendota_kills_log(raw_players, players, slot_by_hero)
        by_slot = {p.player_slot: p for p in players}
        not_deaths = Counter((k.killer_slot, k.victim_slot) for k in reincarnations) + uncounted
        for (killer, victim), n in not_deaths.items():  # take them out of the kill counts as well
            _decrement(by_slot[killer].killed, name_by_slot[victim], n)
            _decrement(by_slot[victim].killed_by, name_by_slot[killer], n)

        raw_fights = _dicts(raw.get("teamfights"))
        teamfights = [self._teamfight(tf, raw_players, heroes) for tf in raw_fights]
        death_windows = []
        for tf_raw, tf in zip(raw_fights, teamfights):
            # OpenDota pads a fight by 15 s around its first and last death.
            first = tf.start_time + 15
            last = _as_int(tf_raw.get("last_death"), tf.end_time - 15)
            death_windows.append((first, last))
            self._reconcile_teamfight(tf, tf_raw, slots, first, last, kills_log, reincarnations)
        _apply_kills_to_teamfights(teamfights, death_windows, kills_log, name_by_slot)

        chat = []
        for msg in _dicts(raw.get("chat")):
            key = str(msg.get("key") if msg.get("key") is not None else "")
            if msg.get("type") == "chatwheel" and not key.startswith("chatwheel_"):
                msg = {**msg, "key": f"chatwheel_{key}"}
            chat.append(msg)

        mode = raw.get("game_mode", 0)
        return MatchData(
            match_id=_as_int(raw.get("match_id")),
            duration=duration,
            radiant_win=bool(raw.get("radiant_win", False)),
            game_mode=game_mode_code(mode),
            start_time=start_time,
            radiant_score=scores["radiant"],
            dire_score=scores["dire"],
            players=players,
            wards=sorted(all_wards, key=lambda w: w.time),
            smokes=[],
            teamfights=teamfights,
            ability_events=[],
            gold_xp_timeline=_gold_xp_timeline(players),
            kills_log=kills_log,
            radiant_gold_adv=_per_minute(raw.get("radiant_gold_adv"), duration),
            radiant_xp_adv=_per_minute(raw.get("radiant_xp_adv"), duration),
            picks_bans=_dicts(raw.get("picks_bans")),
            objectives=[_opendota_objective(o, slots) for o in _dicts(raw.get("objectives"))],
            chat=chat,
            tower_status_radiant=_as_int(raw.get("tower_status_radiant")),
            tower_status_dire=_as_int(raw.get("tower_status_dire")),
            barracks_status_radiant=_as_int(raw.get("barracks_status_radiant")),
            barracks_status_dire=_as_int(raw.get("barracks_status_dire")),
            winner_known=raw.get("radiant_win") is not None,
            first_blood_time=_as_int(raw.get("first_blood_time")),
            cluster=_as_int(raw.get("cluster")),
            region=_as_int(raw.get("region")),
            patch=patch,
            talent_names_patch=talent_names_patch(),
        )

    @staticmethod
    def _death_points(entry: dict) -> list[tuple[float, float, int]]:
        """(x, y, count) world points of a teamfight player's ``deaths_pos`` cells."""
        points = []
        pos = entry.get("deaths_pos")
        if isinstance(pos, dict):
            for cx, ys in pos.items():
                if not isinstance(ys, dict):
                    continue
                for cy, count in ys.items():
                    points.append((geo.opendota_cell_to_world(_as_float(cx)),
                                   geo.opendota_cell_to_world(_as_float(cy)), max(1, _as_int(count, 1))))
        return points

    @classmethod
    def _reconcile_teamfight(cls, tf: TeamfightEvent, tf_raw: dict, slots: list[int], first: float, last: float,
                             kills: list[KillEvent], reincarnations: list[KillEvent]) -> None:
        """Align one teamfight with the reconciled kill log.

        Gives the kills of the fight their position (``deaths_pos`` has no
        times, so only a player who died at a single spot can be placed),
        removes proven reincarnations from the fight's kill and death counts
        and adds deaths the log has but OpenDota's per-player count misses.
        """
        by_slot = {tp.player_slot: tp for tp in tf.players}
        in_fight = [k for k in kills if first - 1 <= k.time <= last + 1]
        for i, entry in enumerate(_dicts(tf_raw.get("players"))):
            points = cls._death_points(entry)
            if len(points) != 1 or i >= len(slots):
                continue
            for k in in_fight:
                if k.victim_slot == slots[i] and k.x is None:
                    k.x, k.y = points[0][0], points[0][1]
        for k in reincarnations:
            if not first - 1 <= k.time <= last + 1:
                continue
            victim, killer = by_slot.get(k.victim_slot), by_slot.get(k.killer_slot)
            if victim is not None and victim.deaths > 0:
                victim.deaths -= 1
            if killer is not None and killer.kills > 0:
                killer.kills -= 1
        logged_deaths = Counter(k.victim_slot for k in in_fight)
        for tp in tf.players:
            tp.deaths = max(tp.deaths, logged_deaths[tp.player_slot])
        tf.radiant_deaths = sum(tp.deaths for tp in tf.players if tp.player_slot < 128)
        tf.dire_deaths = sum(tp.deaths for tp in tf.players if tp.player_slot >= 128)

    @classmethod
    def _teamfight(cls, tf: dict, raw_players: list[dict], heroes: list[tuple[int, str, str]]) -> TeamfightEvent:
        """OpenDota teamfight -> TeamfightEvent (positions from deaths_pos cells).

        ``heroes``: (hero_id, hero_name, hero_slug) of each player, as on its
        PlayerData, so a hero has one name in the whole match.
        """
        tf_entries = _dicts(tf.get("players"))

        all_points = [pt for e in tf_entries for pt in cls._death_points(e)]
        if all_points:
            total = sum(c for _, _, c in all_points)
            center = (sum(x * c for x, _, c in all_points) / total, sum(y * c for _, y, c in all_points) / total)
        else:
            center = (0.0, 0.0)

        players: list[TeamfightPlayer] = []
        r_gold_delta = r_xp_delta = 0
        r_deaths = d_deaths = 0
        for i, tp in enumerate(tf_entries):
            source = raw_players[i] if i < len(raw_players) else {}
            slot = _as_int(source.get("player_slot"), i if i < 5 else 128 + i - 5)
            team = _team_for_slot(slot)
            _hero_id, hero_name, hero_slug = heroes[i] if i < len(heroes) else (0, "", "")
            gold_delta = _as_int(tp.get("gold_delta"))
            xp_delta = _as_int(tp.get("xp_delta"))
            r_gold_delta += gold_delta if team == "radiant" else -gold_delta
            r_xp_delta += xp_delta if team == "radiant" else -xp_delta
            deaths = _as_int(tp.get("deaths"))
            if team == "radiant":
                r_deaths += deaths
            else:
                d_deaths += deaths
            killed = tp.get("killed") if isinstance(tp.get("killed"), dict) else {}
            own_points = cls._death_points(tp)
            if own_points:
                c = sum(n for _, _, n in own_points)
                px = sum(x * n for x, _, n in own_points) / c
                py = sum(y * n for _, y, n in own_points) / c
            else:
                px, py = center
            players.append(TeamfightPlayer(
                player_slot=slot,
                hero_name=hero_name,
                hero_slug=hero_slug,
                x=px,
                y=py,
                damage_dealt=_as_int(tp.get("damage")),
                damage_taken=0,
                healing=_as_int(tp.get("healing")),
                kills=sum(_as_int(v) for v in killed.values()) if killed else _as_int(tp.get("kills")),
                deaths=deaths,
                abilities_used=list((tp.get("ability_uses") or {}).keys()) if isinstance(tp.get("ability_uses"), dict) else [],
                gold_delta=gold_delta,
                xp_delta=xp_delta,
                item_uses=_int_dict(tp.get("item_uses")),
                buybacks=_as_int(tp.get("buybacks")),
            ))
        return TeamfightEvent(
            start_time=_as_int(tf.get("start")),
            end_time=_as_int(tf.get("end")),
            radiant_deaths=r_deaths,
            dire_deaths=d_deaths,
            gold_delta=r_gold_delta,
            xp_delta=r_xp_delta,
            players=players,
        )


def _decrement(counts: dict[str, int], key: str, n: int = 1) -> None:
    if key in counts:
        counts[key] -= n
        if counts[key] <= 0:
            del counts[key]


def _without(counts: dict[str, int], key: str) -> dict[str, int]:
    return {k: v for k, v in counts.items() if k != key}


def _lane_kills(p: dict, team: str) -> int:
    """Enemy lane creeps a player killed, siege creeps included.

    Counted from the ``killed`` breakdown so that it means the same as the
    replay parser's value. OpenDota's own ``lane_kills`` (also the player's
    denies, no siege creeps) only stands in when there is no breakdown.
    """
    killed = p.get("killed")
    if not isinstance(killed, dict) or not killed:
        return _as_int(p.get("lane_kills"))
    enemy = "badguys" if team == "radiant" else "goodguys"
    return sum(_as_int(n) for unit, n in killed.items()
               if f"creep_{enemy}" in str(unit) or f"{enemy}_siege" in str(unit))


def _opendota_kills_log(raw_players: list[dict], players: list[PlayerData],
                        slot_by_hero: dict[str, int]) -> tuple[list[KillEvent], list[KillEvent], Counter]:
    """Kill log from ``players[].kills_log``, reconciled with the scoreboard.

    OpenDota also logs a Wraith King reincarnation as a kill, so a victim can
    have more entries than scoreboard deaths. Returns
    ``(kills, reincarnations, uncounted)``:

    - An entry on such a victim is a proven reincarnation, and left out of
      ``kills``, when its killer has at least as many surplus entries (entries
      minus scoreboard kills) as entries on such victims: the scoreboard never
      counts fewer kills than a hero really landed.
    - A victim that still has more entries than deaths keeps them with
      ``confirmed=False``, except the entries of a killer whose scoreboard
      kills account for every entry he has.
    - ``uncounted[(killer_slot, victim_slot)]`` is how many of those
      unconfirmed entries are reincarnations when only which ones is unknown:
      a killer's surplus that can only be on one such victim.

    Positions are filled in later from the teamfights (None otherwise).
    """
    team = {p.player_slot: p.team for p in players}
    entries: list[KillEvent] = []
    for raw_p, player in zip(raw_players, players):
        for e in _dicts(raw_p.get("kills_log")):
            victim = slot_by_hero.get(normalize_hero_key(e.get("key")))
            if victim is None:
                continue  # not a hero of this match
            entries.append(KillEvent(
                time=_as_float(e.get("time")),
                victim_slot=victim,
                killer_slot=player.player_slot,
                killer_team=player.team,
                deny=team[victim] == player.team,
            ))
    entries.sort(key=lambda k: k.time)

    real = [k for k in entries if not k.deny]
    deaths = {p.player_slot: p.deaths for p in players}
    victim_entries = Counter(k.victim_slot for k in real)
    surplus_victims = {slot for slot, n in victim_entries.items() if n > deaths[slot]}
    if not surplus_victims:
        return entries, [], Counter()

    scoreboard_kills = {p.player_slot: p.kills for p in players}
    killer_surplus = {slot: n - scoreboard_kills[slot] for slot, n in Counter(k.killer_slot for k in real).items()}
    on_surplus = Counter(k.killer_slot for k in real if k.victim_slot in surplus_victims)
    reincarnations = [k for k in real if k.victim_slot in surplus_victims
                      and killer_surplus[k.killer_slot] >= on_surplus[k.killer_slot]]
    kills = [k for k in entries if not any(k is r for r in reincarnations)]
    left = Counter(k.victim_slot for k in kills if not k.deny)
    for k in kills:
        if not k.deny and left[k.victim_slot] > deaths[k.victim_slot] and killer_surplus[k.killer_slot] > 0:
            k.confirmed = False

    unconfirmed = Counter((k.killer_slot, k.victim_slot) for k in kills if not k.confirmed)
    victim_surplus = {slot: left[slot] - deaths[slot] for slot in left}
    uncounted: Counter = Counter()
    for killer in sorted({k for k, _v in unconfirmed}):
        victims = [v for k, v in unconfirmed if k == killer]
        if len(victims) != 1:
            continue  # the surplus could be on either victim
        n = min(killer_surplus[killer], unconfirmed[(killer, victims[0])], victim_surplus[victims[0]])
        if n > 0:
            uncounted[(killer, victims[0])] = n
            victim_surplus[victims[0]] -= n
    return kills, reincarnations, uncounted


# Valve team ids, as OpenDota sends them on Roshan and courier objectives
_TEAM_CODES = {2: "radiant", 3: "dire"}


def _opendota_objective(obj: dict, slots: list[int]) -> dict:
    """OpenDota objective -> contract shape (team codes, building teams, slots)."""
    out = dict(_annotate_building_objective(obj))
    team = out.get("team")
    if isinstance(team, int) and not isinstance(team, bool):
        if team in _TEAM_CODES:
            out["team"] = _TEAM_CODES[team]
        else:
            del out["team"]
    if out.get("type") == "CHAT_MESSAGE_COURIER_LOST":
        # "killer" is the player index (0-9) of the hero that killed it, -1 for none.
        killer = _as_int(out.pop("killer", None), -1)
        if 0 <= killer < len(slots) and out.get("player_slot") is None:
            out["player_slot"] = slots[killer]
        return out
    if out.get("type") != "CHAT_MESSAGE_FIRSTBLOOD":
        return out
    victim = out.get("victim_player_slot")
    if victim is None and out.get("key") is not None:
        # Older responses only carry the victim's player index (0-9) in "key".
        idx = _as_int(out.get("key"), -1)
        victim = slots[idx] if 0 <= idx < len(slots) else None
    out.pop("key", None)
    if victim is not None:
        out["key"] = str(_as_int(victim))
    return out


def _patch_name(patch_id: Any, patches: list[dict]) -> str:
    """Game version ("7.41") for an OpenDota patch id; "" when it cannot be resolved."""
    if patch_id is None or isinstance(patch_id, bool):
        return ""
    for patch in patches:
        if str(patch.get("id")) == str(patch_id) and patch.get("name"):
            return str(patch["name"])
    return ""


def _stored_patch(start_time: int) -> str:
    """Game version the stored game data (data layer) has for a match's start
    time; "" when it cannot tell. No network."""
    by_time = _data_layer("patch_for_time")
    return str(by_time(start_time) or "") if by_time is not None and start_time > 0 else ""


def _match_patch(patch_id: Any, patches: list[dict], start_time: int) -> str:
    """Game version of an OpenDota match: its patch id through the patch
    table, else (table not available) the version the stored game data has
    for the match's start time; "" when neither tells.

    Both name the same version: OpenDota derives the id from the start time
    and its own copy of that table.
    """
    name = _patch_name(patch_id, patches)
    if name or patch_id is None or isinstance(patch_id, bool):
        return name
    return _stored_patch(start_time)


